class TestNewErrorDiff(EmbodyTestCase):

    def _entries(self, *paths):
        return [{'nodePath': p, 'message': 'boom at ' + p} for p in paths]

    def test_first_write_establishes_baseline_only(self):
        listed, total, paths = _envoy_mod._new_error_entries(
            None, self._entries('/a', '/b'), 3)
        self.assertEqual(listed, [])
        self.assertEqual(total, 0)
        self.assertEqual(paths, {'/a', '/b'})

    def test_only_additions_reported(self):
        listed, total, paths = _envoy_mod._new_error_entries(
            {'/a'}, self._entries('/a', '/b'), 3)
        self.assertEqual(total, 1)
        self.assertEqual(listed[0]['path'], '/b')
        self.assertEqual(paths, {'/a', '/b'})

    def test_disappearing_errors_are_not_reported(self):
        listed, total, paths = _envoy_mod._new_error_entries(
            {'/a', '/b'}, self._entries('/a'), 3)
        self.assertEqual(listed, [])
        self.assertEqual(total, 0)
        self.assertEqual(paths, {'/a'})

    def test_cap_limits_list_but_not_the_count(self):
        listed, total, _paths = _envoy_mod._new_error_entries(
            set(), self._entries('/a', '/b', '/c', '/d', '/e'), 3)
        self.assertLen(listed, 3)
        self.assertEqual(total, 5)

    def test_repeated_messages_on_one_op_collapse(self):
        entries = [{'nodePath': '/a', 'message': 'one'},
                   {'nodePath': '/a', 'message': 'two'}]
        listed, total, _paths = _envoy_mod._new_error_entries(
            set(), entries, 3)
        self.assertLen(listed, 1)
        self.assertEqual(total, 1)

    def test_malformed_entries_are_skipped(self):
        entries = [None, 'nonsense', {}, {'nodePath': ''},
                   {'nodePath': '/ok', 'message': 'm'}]
        listed, total, paths = _envoy_mod._new_error_entries(
            set(), entries, 3)
        self.assertEqual(paths, {'/ok'})
        self.assertEqual(total, 1)
        self.assertEqual(listed[0]['path'], '/ok')

    def test_none_input_is_empty(self):
        listed, total, paths = _envoy_mod._new_error_entries(set(), None, 3)
        self.assertEqual((listed, total, paths), ([], 0, set()))

    def test_message_is_length_capped(self):
        entries = [{'nodePath': '/a', 'message': 'x' * 500}]
        listed, _total, _paths = _envoy_mod._new_error_entries(
            set(), entries, 3)
        self.assertLen(listed[0]['message'], 200)


class TestFpsRegression(EmbodyTestCase):

    def test_meaningful_drop_reported(self):
        drop = _envoy_mod._fps_regression(60.0, 20.0)
        self.assertEqual(drop['was'], 60.0)
        self.assertEqual(drop['now'], 20.0)
        self.assertEqual(drop['drop_pct'], 67)

    def test_jitter_is_silent(self):
        self.assertEqual(_envoy_mod._fps_regression(60.0, 59.0), {})
        self.assertEqual(_envoy_mod._fps_regression(60.0, 58.0), {})

    def test_proportional_but_tiny_absolute_drop_is_silent(self):
        # 10 -> 8 is a 20% drop but only 2 fps: below the absolute floor.
        self.assertEqual(_envoy_mod._fps_regression(10.0, 8.0), {})

    def test_improvement_is_silent(self):
        self.assertEqual(_envoy_mod._fps_regression(20.0, 60.0), {})

    def test_missing_or_bogus_samples_are_silent(self):
        self.assertEqual(_envoy_mod._fps_regression(None, 30.0), {})
        self.assertEqual(_envoy_mod._fps_regression(60.0, None), {})
        self.assertEqual(_envoy_mod._fps_regression('x', 30.0), {})
        self.assertEqual(_envoy_mod._fps_regression(0.0, 30.0), {})
        self.assertEqual(_envoy_mod._fps_regression(60.0, 0.0), {})


