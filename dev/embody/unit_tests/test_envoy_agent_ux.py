class TestFocusTargetRule(EmbodyTestCase):
    """The disambiguation rule, pure: "this operator" is the selected /
    current op, NEVER the rollover."""

    def test_single_selection_wins(self):
        self.assertEqual(_read_mod.focus_target(['/a/x'], '/a/y'),
                         ('/a/x', 'selection'))

    def test_current_used_when_selection_is_ambiguous(self):
        self.assertEqual(_read_mod.focus_target(['/a/x', '/a/y'], '/a/y'),
                         ('/a/y', 'current'))

    def test_current_used_when_nothing_selected(self):
        self.assertEqual(_read_mod.focus_target([], '/a/y'),
                         ('/a/y', 'current'))

    def test_ambiguous_multi_selection_without_current(self):
        self.assertEqual(_read_mod.focus_target(['/a/x', '/a/y'], None),
                         (None, None))

    def test_nothing_at_all(self):
        self.assertEqual(_read_mod.focus_target([], None), (None, None))
        self.assertEqual(_read_mod.focus_target(None, None), (None, None))


class TestGetFocus(EmbodyTestCase):

    def setUp(self):
        super().setUp()
        self.envoy = self.embody.ext.Envoy

    def _focus(self):
        return self.envoy._get_focus()

    def test_returns_the_documented_shape(self):
        result = self._focus()
        self.assertNotIn('error', result)
        for key in ('network', 'selected', 'selectedCount', 'current',
                    'rollover', 'target', 'targetSource', 'note'):
            self.assertDictHasKey(result, key)
        self.assertIsInstance(result['selected'], list)

    def test_never_targets_the_rollover_op(self):
        result = self._focus()
        target = result.get('target')
        if target is None:
            return
        self.assertTrue(
            target == result.get('current') or target in result['selected'],
            'target must come from the selection/current op, never rollover')

    def test_target_is_consistent_with_the_reported_selection(self):
        result = self._focus()
        target, source = _read_mod.focus_target(
            result.get('selected'), result.get('current'))
        self.assertEqual(result.get('target'), target)
        self.assertEqual(result.get('targetSource'), source)

    def test_dispatches_through_the_operation_router(self):
        result = self.envoy._execute_operation('get_focus', {})
        self.assertIsInstance(result, dict)
        self.assertNotIn('Unknown operation', str(result.get('error', '')))
