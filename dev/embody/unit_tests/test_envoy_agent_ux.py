class _BrokenExt:
    """Stand-in ext with no _effects_state -- _attachEffects must degrade
    silently rather than raise through the response chokepoint."""
    ownerComp = None


class TestEffectsAttachGuards(EmbodyTestCase):

    SID = '_tc_effects_sid'

    def setUp(self):
        super().setUp()
        self.envoy = self.embody.ext.Envoy
        self.assertTrue(hasattr(self.envoy, '_effects_state'),
                        'running EnvoyExt predates the write-effect footer')
        self.envoy._effects_state.pop(self.SID, None)
        self._scan_ok = getattr(self.envoy, '_effects_error_scan_ok', True)
        self.envoy._effects_error_scan_ok = True

    def tearDown(self):
        self.envoy._effects_state.pop(self.SID, None)
        self.envoy._effects_error_scan_ok = self._scan_ok
        super().tearDown()

    def test_read_operations_never_get_a_footer(self):
        result = {'ok': True}
        self.envoy._attachEffects(result, 'get_op', self.SID)
        self.assertEqual(result, {'ok': True})
        self.assertNotIn(self.SID, self.envoy._effects_state)

    def test_missing_operation_never_gets_a_footer(self):
        result = {'ok': True}
        self.envoy._attachEffects(result, None, self.SID)
        self.assertNotIn('_effects', result)

    def test_non_dict_result_does_not_raise(self):
        self.envoy._attachEffects('not a dict', 'create_op', self.SID)
        self.envoy._attachEffects(None, 'create_op', self.SID)

    def test_existing_effects_key_is_not_clobbered(self):
        result = {'_effects': {'mine': 1}}
        self.envoy._attachEffects(result, 'create_op', self.SID)
        self.assertEqual(result['_effects'], {'mine': 1})

    def test_broken_ext_degrades_silently(self):
        result = {'ok': True}
        type(self.envoy)._attachEffects(
            _BrokenExt(), result, 'create_op', self.SID)
        self.assertNotIn('_effects', result)

    def test_first_write_only_baselines(self):
        # A session's first write must never report the project's
        # PRE-EXISTING errors as newly introduced.
        result = {'ok': True}
        self.envoy._attachEffects(result, 'create_op', self.SID)
        self.assertNotIn('_effects', result)
        self.assertIn(self.SID, self.envoy._effects_state)
        state = self.envoy._effects_state[self.SID]
        self.assertIsInstance(state.get('errors'), set)

    def test_disabled_error_scan_is_skipped_not_fatal(self):
        # The budget valve: once the project-wide scan is disabled for the
        # session, writes still respond -- just without the error half.
        self.envoy._effects_error_scan_ok = False
        result = {'ok': True}
        self.envoy._attachEffects(result, 'create_op', self.SID)
        self.assertNotIn('_effects', result)
        state = self.envoy._effects_state.get(self.SID, {})
        self.assertNotIn('errors', state)

    def test_fps_sample_never_creates_an_operator(self):
        # get_project_performance may create its monitor on first call;
        # the footer must only READ an existing one.
        before = [c.name for c in self.embody.children]
        self.envoy._sampleProjectFps()
        self.assertEqual([c.name for c in self.embody.children], before)


