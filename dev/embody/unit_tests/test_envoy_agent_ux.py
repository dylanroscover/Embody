class TestGuidanceScanAndBody(EmbodyTestCase):

    def _worker_on(self, claude_dir):
        w = _bare_worker()
        # Shadow the search so the test never picks up this repo's real
        # .claude via the cwd fallback.
        w._guidanceSearchDirs = lambda: [claude_dir]
        return w

    def test_scan_indexes_rules_and_skills(self):
        with tempfile.TemporaryDirectory() as td:
            claude = _make_claude_tree(
                td, rules={'network-layout': RULE_DOC},
                skills={'create-operator': SKILL_DOC})
            index = _envoy_mod.EnvoyMCPServer._guidanceScanDir(claude)
            self.assertIn('network-layout', index)
            self.assertIn('create-operator', index)
            self.assertEqual(index['network-layout']['kind'], 'rule')
            self.assertEqual(index['create-operator']['kind'], 'skill')
            self.assertEqual(index['network-layout']['description'],
                             'Network Layout Conventions')

    def test_scan_missing_directory_is_empty_not_raising(self):
        with tempfile.TemporaryDirectory() as td:
            index = _envoy_mod.EnvoyMCPServer._guidanceScanDir(
                os.path.join(td, 'nope', '.claude'))
            self.assertEqual(index, {})

    def test_scan_skips_empty_and_non_markdown(self):
        with tempfile.TemporaryDirectory() as td:
            claude = _make_claude_tree(td, rules={'good': RULE_DOC})
            rules_dir = os.path.join(claude, 'rules')
            with open(os.path.join(rules_dir, 'blank.md'), 'w',
                      encoding='utf-8') as f:
                f.write('   \n')
            with open(os.path.join(rules_dir, 'notes.txt'), 'w',
                      encoding='utf-8') as f:
                f.write('# ignored')
            index = _envoy_mod.EnvoyMCPServer._guidanceScanDir(claude)
            self.assertEqual(sorted(index), ['good'])

    def test_scan_disambiguates_rule_skill_slug_collision(self):
        with tempfile.TemporaryDirectory() as td:
            claude = _make_claude_tree(
                td, rules={'parameters': RULE_DOC},
                skills={'parameters': SKILL_DOC})
            index = _envoy_mod.EnvoyMCPServer._guidanceScanDir(claude)
            self.assertEqual(len(index), 2,
                             'a slug collision must keep both documents')
            self.assertIn('parameters', index)

    def test_bare_call_lists_topics(self):
        with tempfile.TemporaryDirectory() as td:
            claude = _make_claude_tree(
                td, rules={'network-layout': RULE_DOC},
                skills={'create-operator': SKILL_DOC})
            result = self._worker_on(claude)._get_guidance()
            self.assertEqual(result['count'], 2)
            self.assertNotIn('error', result)
            topics = {t['topic']: t for t in result['topics']}
            self.assertEqual(topics['network-layout']['kind'], 'rule')
            self.assertEqual(topics['create-operator']['kind'], 'skill')
            self.assertTrue(result['usage'])

    def test_topic_call_returns_content(self):
        with tempfile.TemporaryDirectory() as td:
            claude = _make_claude_tree(
                td, skills={'create-operator': SKILL_DOC})
            result = self._worker_on(claude)._get_guidance('create_operator')
            self.assertEqual(result['topic'], 'create-operator')
            self.assertEqual(result['kind'], 'skill')
            self.assertIn('Create Operator Workflow', result['content'])
            self.assertNotIn('truncated', result)

    def test_long_document_is_truncated_and_says_so(self):
        with tempfile.TemporaryDirectory() as td:
            long_doc = '# Big\n\n' + ('x' * (_envoy_mod._GUIDANCE_MAX_CHARS + 500))
            claude = _make_claude_tree(td, rules={'big': long_doc})
            result = self._worker_on(claude)._get_guidance('big')
            self.assertTrue(result['truncated'])
            self.assertLen(result['content'], _envoy_mod._GUIDANCE_MAX_CHARS)
            self.assertIn('truncated', result['note'].lower())

    def test_unknown_topic_returns_list_and_did_you_mean(self):
        with tempfile.TemporaryDirectory() as td:
            claude = _make_claude_tree(
                td, skills={'create-operator': SKILL_DOC})
            result = self._worker_on(claude)._get_guidance('creat-operatr')
            self.assertIn('error', result)
            self.assertIn('create-operator', result['did_you_mean'])
            self.assertEqual(result['count'], 1)

    def test_no_docs_anywhere_returns_actionable_error(self):
        with tempfile.TemporaryDirectory() as td:
            missing = os.path.join(td, '.claude')
            result = self._worker_on(missing)._get_guidance()
            self.assertIn('error', result)
            self.assertIn('InitEnvoy', result['action'])
            self.assertEqual(result['searched'], [missing])

    def test_index_is_cached_within_ttl(self):
        with tempfile.TemporaryDirectory() as td:
            claude = _make_claude_tree(td, rules={'one': RULE_DOC})
            w = self._worker_on(claude)
            self.assertEqual(w._get_guidance()['count'], 1)
            with open(os.path.join(claude, 'rules', 'two.md'), 'w',
                      encoding='utf-8') as f:
                f.write(RULE_DOC)
            self.assertEqual(w._get_guidance()['count'], 1,
                             'index must be served from cache inside the TTL')
            w._guidance_state['ts'] = 0.0  # force expiry
            self.assertEqual(w._get_guidance()['count'], 2)

    def test_search_dirs_lead_with_the_repo_root(self):
        w = _bare_worker()
        sentinel = os.path.join(tempfile.gettempdir(), '_tc_guidance_root')
        had = hasattr(sys, '_envoy_repo_root')
        previous = getattr(sys, '_envoy_repo_root', None)
        try:
            sys._envoy_repo_root = sentinel
            dirs = w._guidanceSearchDirs()
        finally:
            if had:
                sys._envoy_repo_root = previous
            else:
                try:
                    del sys._envoy_repo_root
                except AttributeError:
                    pass
        self.assertEqual(dirs[0], os.path.join(sentinel, '.claude'))
        self.assertGreater(len(dirs), 1, 'ancestors/cwd fallbacks missing')


