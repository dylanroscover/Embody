def _bare_worker():
    """EnvoyMCPServer carrying only the guidance state, skipping __init__
    (which imports the MCP SDK and registers every tool)."""
    W = _envoy_mod.EnvoyMCPServer
    w = W.__new__(W)
    w._guidance_state = {'ts': 0.0, 'root': None, 'index': None,
                         'searched': []}
    return w


def _make_claude_tree(base, rules=None, skills=None):
    """Write a .claude/rules + .claude/skills tree under `base`; return the
    .claude directory."""
    claude = os.path.join(base, '.claude')
    rules_dir = os.path.join(claude, 'rules')
    skills_dir = os.path.join(claude, 'skills')
    os.makedirs(rules_dir)
    os.makedirs(skills_dir)
    for name, text in (rules or {}).items():
        with open(os.path.join(rules_dir, name + '.md'), 'w',
                  encoding='utf-8') as f:
            f.write(text)
    for slug, text in (skills or {}).items():
        slug_dir = os.path.join(skills_dir, slug)
        os.makedirs(slug_dir)
        with open(os.path.join(slug_dir, 'SKILL.md'), 'w',
                  encoding='utf-8') as f:
            f.write(text)
    return claude


