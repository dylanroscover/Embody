"""
Test suite: the release smoke's `uninstall` leg (smoke_legs/uninstall.py).

Pure Python, TD-import-free: the leg is orchestrator-side code, loaded by
file path and driven against a scripted stand-in for the smoke TD -- a
fake clock, a fake Envoy port, and a REAL temp run directory holding the
files Uninstall touches. Inside TD every test skips.

What this pins, assertion by assertion, is that the PROOF is load-bearing.
For every claim the leg makes there is a fake uninstall that breaks it and
must turn the leg red:
- a user file deleted, or a user MCP server stripped out of .mcp.json;
- .embody/ or the .venv left behind; an externalized .tdxn removed;
- a 'review' item deleted; settings.local.json rewritten;
- a plan that omits a manifest-recorded path, or lists a user file;
- a plan rooted anywhere but the run dir (refused BEFORE anything runs);
- a summary that never appears, or says ran=False (the confirm cancelled);
- an Envoy that outlives its own uninstall;
- any change to a repo-checkout witness file.
Plus the contract: run() never raises, every seeded dialog title is a real
title in embody_admin.py, the uninstall is deferred through TD's own run()
(execute_python has no `run` in its namespace), and nothing quits TD.
"""

