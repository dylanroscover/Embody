class _FakeTD:
    """The smoke instance as the leg can observe it: a fake clock, a port
    that stops answering when Uninstall runs, the plan PreviewUninstall
    returns, and a fake executor that consumes that plan against the real
    temp run dir. Every recovery the leg checks is a switch a test flips."""

    # rel -> content. The install as the smoke leaves it.
    GENERATED = ('CLAUDE.md', 'AGENTS.md', '.claude/rules/embody-rule.md',
                 '.claude/skills/embody-skill/SKILL.md', '.embody/config.json')
    USER_KEPT = ('externalized/comp.tdxn', 'externalized/comp.tox',
                 'externalized/ext.py', 'externalizations.tsv',
                 'smoke_template.toe', 'logs/embody.log')
    VENV_FILES = ('.venv/pyvenv.cfg', '.venv/Scripts/python.exe')
    EMPTY_DIRS = ('.claude/skills/embody-skill', '.claude/skills',
                  '.claude/rules', '.claude')

    def __init__(self, run_dir, repo, port=9871, pid=4242):
        self.run_dir = run_dir
        self.repo = repo
        self.port = port
        self.pid = pid
        self.now = 1000.0
        self.budget_left = 3600.0
        self.project_folder = run_dir
        self.envoy_up = True
        self.scripts = []
        self.waits = []
        self.logs = []
        self.files = []          # every file this fake created
        # switches
        self.execute = True
        self.write_summary = True
        self.summary = {'ran': True, 'deleted': 9, 'stripped': 2,
                        'unset': 2, 'kept_review': 1, 'errors': 0}
        self.delete_user_file = False
        self.delete_user_rule = False
        self.tamper_user_file = False
        self.delete_tdxn = False
        self.keep_embody_dir = False
        self.keep_venv = False
        # Embody's own post-uninstall settings save, which mkdirs .embody/
        # again to write config.json. On by default: it is what really
        # happens, so the happy path has to tolerate it.
        self.reborn_config = True
        self.leave_state = ()
        self.reborn_manifest = False
        self.leave_planned = None
        self.strip_user_server = False
        self.remove_mcp_json = False
        self.delete_review = False
        self.mutate_settings = False
        self.append_settings = False
        self.touch_repo = False
        self.envoy_survives = False
        self.plan_omit = None
        self.plan_extra_delete = None
        self.plan_root = None
        self.wiring = {'style': 'Pulse', 'routers': ['parexec']}
        self._install()

    # --- the installed project ---------------------------------------

    def _put(self, rel, text):
        _write(os.path.join(self.run_dir, rel), text)
        if rel not in self.files:
            self.files.append(rel)

    def _install(self):
        for rel in self.GENERATED:
            self._put(rel, _MARKER % 'abc123' + 'generated %s\n' % rel)
        for rel in self.USER_KEPT:
            self._put(rel, 'user content for %s\n' % rel)
        for rel in self.VENV_FILES:
            self._put(rel, 'venv file\n')
        self._put('.gitignore', 'build/\n\n# Embody / Envoy (auto-managed)\n'
                                '.embody/\n')
        self._put('.mcp.json', json.dumps({'mcpServers': {'envoy': {
            'type': 'stdio', 'command': '.venv/python', 'args': []}}},
            indent=2) + '\n')
        self._put('.claude/settings.local.json', json.dumps(
            {'permissions': {'allow': ['mcp__envoy__query_network']}},
            indent=2) + '\n')
        self._put('.embody/config.json',
                  json.dumps({'version': 1, 'params': {}}, indent=2) + '\n')
        self._put('.embody/hashes.json', json.dumps({'CLAUDE.md': 'abc'}) + '\n')
        self._put('.embody/manifest.json', json.dumps({
            'version': 1,
            'files_created': list(self.GENERATED) + [
                '.mcp.json', '.claude/settings.local.json', 'gone.md'],
            'files_appended': [{'path': '.gitignore',
                                'marker': '# Embody / Envoy',
                                'kind': 'block'}],
            'git_config': ['diff.tdxn.textconv'],
            'venv': {'path': '.venv', 'created': True},
            'network_ops': []}, indent=2, sort_keys=True) + '\n')

    # --- the plan PreviewUninstall returns ----------------------------

    def plan(self):
        delete = [{'path': rel, 'kind': 'file', 'why': 'Embody-generated'}
                  for rel in self.GENERATED]
        delete.append({'path': '.venv', 'kind': 'dir', 'why': 'Embody venv'})
        delete.append({'path': '.embody', 'kind': 'dir',
                       'why': 'Embody runtime state'})
        delete += [{'path': rel, 'kind': 'emptydir', 'why': 'removed if empty'}
                   for rel in self.EMPTY_DIRS]
        if self.plan_extra_delete:
            delete.append({'path': self.plan_extra_delete, 'kind': 'file',
                           'why': 'injected by a test'})
        if self.plan_omit:
            delete = [e for e in delete if e['path'] != self.plan_omit]
        return {
            'root': self.plan_root or self.run_dir,
            'sources': ['manifest', 'fallback'],
            'delete': delete,
            'strip': [{'path': '.mcp.json', 'kind': 'mcp_config',
                       'marker': 'mcpServers.envoy', 'why': 'key only'},
                      {'path': '.gitignore', 'kind': 'block',
                       'marker': '# Embody / Envoy', 'why': 'block only'}],
            'unset': ['diff.tdxn.textconv', 'diff.tdxn.cachetextconv'],
            'review': [{'path': '.claude/settings.local.json',
                        'why': 'may hold your permission edits -- kept'}],
            'missing': ['gone.md'],
        }

    # --- the fake executor --------------------------------------------

    def _rm(self, rel):
        path = os.path.join(self.run_dir, rel)
        if os.path.isfile(path):
            os.remove(path)

    def _rm_dir(self, rel):
        """Remove the files this fake created under `rel`, then its
        directories deepest-first. Enumerated, never a recursive sweep."""
        prefix = rel.rstrip('/') + '/'
        dirs = set()
        for tracked in list(self.files):
            if tracked.startswith(prefix):
                self._rm(tracked)
                part = os.path.dirname(tracked)
                while part and part != rel:
                    dirs.add(part)
                    part = os.path.dirname(part)
        for part in sorted(dirs, key=lambda d: -d.count('/')) + [rel]:
            try:
                os.rmdir(os.path.join(self.run_dir, part))
            except OSError:
                pass

    def _rmdir_if_empty(self, rel):
        try:
            os.rmdir(os.path.join(self.run_dir, rel))
        except OSError:
            pass

    def uninstall(self):
        """What embody_admin.execute_uninstall_plan does, on this fixture."""
        plan = self.plan()
        for entry in plan['delete']:
            rel, kind = entry['path'], entry.get('kind')
            if rel == self.leave_planned or kind == 'emptydir':
                continue
            if rel == '.embody' and self.keep_embody_dir:
                continue
            if rel == '.venv' and self.keep_venv:
                continue
            if kind == 'dir':
                self._rm_dir(rel)
            else:
                self._rm(rel)
        if not self.keep_embody_dir:
            # the deferred _saveSettings landing one frame after the delete
            if self.reborn_config:
                _write(os.path.join(self.run_dir, '.embody/config.json'),
                       json.dumps({'version': 1, 'params': {
                           'Envoyenable': {'val': 0}}}, indent=2) + '\n')
            if self.reborn_manifest:
                _write(os.path.join(self.run_dir, '.embody/manifest.json'),
                       '{}\n')
            for rel in self.leave_state:
                _write(os.path.join(self.run_dir, rel), 'left behind\n')
        if self.remove_mcp_json:
            self._rm('.mcp.json')
        else:
            cfg = json.loads(_read(os.path.join(self.run_dir, '.mcp.json')))
            servers = cfg.get('mcpServers', {})
            servers.pop('envoy', None)
            if self.strip_user_server:
                servers.clear()
            _write(os.path.join(self.run_dir, '.mcp.json'),
                   json.dumps(cfg, indent=2) + '\n')
        _write(os.path.join(self.run_dir, '.gitignore'), 'build/\n')
        for rel in self.EMPTY_DIRS:
            self._rmdir_if_empty(rel)
        if self.delete_user_file:
            self._rm(leg.USER_FILE)
        if self.delete_user_rule:
            self._rm(leg.USER_RULE)
        if self.tamper_user_file:
            _write(os.path.join(self.run_dir, leg.USER_FILE),
                   leg.USER_NOTES_TEXT + 'appended by the uninstall\n')
        if self.delete_tdxn:
            self._rm('externalized/comp.tdxn')
        if self.delete_review:
            self._rm('.claude/settings.local.json')
        if self.mutate_settings or self.append_settings:
            path = os.path.join(self.run_dir, '.claude/settings.local.json')
            data = json.loads(_read(path))
            if self.mutate_settings:
                data.pop(leg.USER_SETTING, None)
            if self.append_settings:
                data['rewrittenByUninstall'] = True
            _write(path, json.dumps(data, indent=2) + '\n')
        if self.touch_repo:
            _write(os.path.join(self.repo, 'CLAUDE.md'),
                   'the smoke reached outside its run dir\n')
        if not self.envoy_survives:
            self.envoy_up = False
        if self.write_summary:
            _write(os.path.join(self.run_dir, leg.SUMMARY_FILE),
                   json.dumps(self.summary))

    # --- the ctx callables ---------------------------------------------

    def py(self, code, timeout=30):
        code = str(code)
        if 'result = project.folder' in code:
            return self.project_folder
        if 'PreviewUninstall' in code:
            return json.dumps(self.plan())
        if "_out['routers']" in code:
            return json.dumps(self.wiring)
        if 'from td import run as _run' in code:
            self.scripts.append(code)
            if self.execute:
                self.uninstall()
            return 'scheduled'
        if code.strip() == 'result = 1':
            if not self.envoy_up:
                raise RuntimeError('execute_python: connection refused')
            return '1'
        raise AssertionError('unscripted execute_python: %r' % code[:90])

    def call(self, name, arguments, timeout=30):
        raise AssertionError('the uninstall leg makes no tool calls: %s'
                             % name)

    def wait_for_flag(self, name, timeout, done):
        self.waits.append({'name': name, 'timeout': timeout})
        self.now += float(timeout)
        path = os.path.join(self.run_dir, name)
        if not os.path.isfile(path):
            return None, False
        text = _read(path)
        return text, bool(done(text))

    # --- the fake clock the leg's waits run on ------------------------

    def clock(self):
        return self.now

    def sleep(self, dt):
        self.now += max(float(dt), 0.001)

    def ctx(self):
        return {'run_dir': self.run_dir, 'repo': self.repo,
                'build': {'version': '6.2.57'},
                'installed': {'version': '6.2.57'}, 'upgrade_from': None,
                'port': self.port, 'set_port': lambda p: None,
                'pid': self.pid, 'td_exe': 'td.exe', 'platform': 'win32',
                'call': self.call, 'py': self.py,
                'log': self.logs.append,
                'budget': lambda: self.budget_left - (self.now - 1000.0),
                'wait_for_flag': self.wait_for_flag,
                '_seams': {'clock': self.clock, 'sleep': self.sleep}}


class _Case(EmbodyTestCase):

    def setUp(self):
        super().setUp()
        if _IN_TD:
            self.skipTest('pure-Python suite -- runs under pytest/CI only')
        self.root = tempfile.mkdtemp(prefix='embody_smoke_uninstall_')
        self.run_dir = os.path.join(self.root, 'run')
        self.repo = os.path.join(self.root, 'repo')
        os.makedirs(self.run_dir, exist_ok=True)
        for rel in ('CLAUDE.md', 'AGENTS.md', '.gitignore', '.gitattributes'):
            _write(os.path.join(self.repo, rel), 'checkout %s\n' % rel)
        self.td = _FakeTD(self.run_dir, self.repo)

    # helpers
    def go(self):
        self.result = leg.run(self.td.ctx())
        return self.result

    def step(self, name):
        for s in self.result['steps']:
            if s['step'] == name:
                return s
        return None

    def names(self):
        return [s['step'] for s in self.result['steps']]

    def assertStepOk(self, name):
        got = self.step(name)
        self.assertIsNotNone(got, '%s never ran: %s' % (name, self.names()))
        self.assertTrue(got['ok'], '%s failed: %s' % (name, got['detail']))

    def assertStepFailed(self, name):
        got = self.step(name)
        self.assertIsNotNone(got, '%s never ran: %s' % (name, self.names()))
        self.assertFalse(got['ok'], '%s unexpectedly passed: %s'
                         % (name, got['detail']))
        self.assertFalse(self.result['ok'], 'the leg reported ok anyway')

    def exists(self, rel):
        return os.path.exists(os.path.join(self.run_dir, rel))


