class TestSafetyFences(_Case):

    def test_a_port_serving_another_project_plants_nothing(self):
        self.td.project_folder = os.path.join(self.root, 'someone-else')
        os.makedirs(self.td.project_folder, exist_ok=True)
        res = self.go()
        self.assertStepFailed('leg.target')
        self.assertIn('refusing', res['error'])
        self.assertFalse(self.exists(leg.USER_FILE))
        self.assertEqual(self.td.scripts, [], 'it uninstalled anyway')
        self.assertEqual(self.names(), ['leg.target'])

    def test_an_unreadable_project_folder_fails_the_gate(self):
        def boom(code, timeout=30):
            raise RuntimeError('connection refused')
        self.td.py = boom
        self.go()
        self.assertStepFailed('leg.target')

    def test_a_plan_rooted_outside_the_run_dir_is_refused(self):
        before = _tree(self.repo)
        self.td.plan_root = self.repo
        res = self.go()
        self.assertStepFailed('plan_root_is_run_dir')
        self.assertIn('refusing to run Uninstall', res['error'])
        self.assertEqual(self.td.scripts, [], 'it uninstalled anyway')
        self.assertEqual(_tree(self.repo), before)

    def test_a_repo_witness_file_that_changes_fails_the_leg(self):
        self.td.touch_repo = True
        self.go()
        self.assertStepFailed('outside_run_dir_untouched')
        self.assertIn('CLAUDE.md', self.step(
            'outside_run_dir_untouched')['detail'])

    def test_missing_repo_witness_files_are_handled_not_crashed_on(self):
        """.mcp.json, .claude/settings.local.json and .embody/manifest.json
        are gitignored: absent on a fresh clone, and absent on both sides."""
        for rel in ('.mcp.json', '.claude/settings.local.json',
                    '.embody/manifest.json'):
            self.assertFalse(os.path.exists(os.path.join(self.repo, rel)))
        self.go()
        self.assertStepOk('repo_baseline')
        self.assertStepOk('outside_run_dir_untouched')

    def test_a_repo_with_no_witness_files_is_not_a_fence(self):
        self.td.repo = os.path.join(self.root, 'empty-repo')
        os.makedirs(self.td.repo, exist_ok=True)
        self.go()
        self.assertStepFailed('repo_baseline')

    def test_no_repo_in_ctx_skips_the_fence_without_failing(self):
        self.td.repo = ''
        self.go()
        self.assertStepOk('repo_baseline')
        self.assertIn('not available', self.step('repo_baseline')['detail'])

    def test_the_leg_writes_nothing_outside_the_run_dir(self):
        before = _tree(self.repo)
        self.td.execute = False
        self.go()
        self.assertEqual(_tree(self.repo), before)

    def test_the_leg_itself_creates_only_its_planted_files(self):
        self.td.execute = False       # nothing deleted: the delta is the leg's
        before = _tree(self.run_dir)
        self.go()
        after = _tree(self.run_dir)
        self.assertEqual(sorted(set(after) - set(before)),
                         [leg.USER_RULE, leg.USER_FILE])
        self.assertEqual(sorted(set(before) - set(after)), [])
        changed = sorted(k for k in before if before[k] != after.get(k))
        self.assertEqual(changed, ['.claude/settings.local.json',
                                   '.mcp.json'])


