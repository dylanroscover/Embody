class TestHappyPath(_Case):

    def test_a_faithful_uninstall_passes_every_step(self):
        res = self.go()
        self.assertTrue(res['ok'], 'leg failed: %s / %s'
                        % (res['error'], [s for s in res['steps']
                                          if not s['ok']]))
        self.assertEqual(res['error'], '')
        for name in ('leg.target', 'plant_user_content', 'repo_baseline',
                     'uninstall_button_wired', 'preview_plan',
                     'plan_root_is_run_dir', 'plan_covers_manifest',
                     'plan_removes_state_and_venv', 'plan_spares_user_files',
                     'leaves_td_running', 'uninstall_ran', 'envoy_stopped',
                     'generated_removed', 'user_files_intact',
                     'mcp_json_reversed', 'review_items_kept',
                     'settings_local_kept', 'venv_removed',
                     'embody_state_removed', 'untouched_paths_kept',
                     'outside_run_dir_untouched'):
            self.assertStepOk(name)

    def test_result_matches_the_leg_contract(self):
        res = self.go()
        self.assertEqual(sorted(res), ['error', 'ok', 'steps'])
        self.assertIsInstance(res['ok'], bool)
        for s in res['steps']:
            self.assertEqual(sorted(s), ['detail', 'ok', 'step'])
            self.assertIsInstance(s['ok'], bool)
            self.assertIsInstance(s['detail'], str)

    def test_the_planted_user_content_is_really_planted(self):
        self.go()
        self.assertTrue(self.exists(leg.USER_FILE))
        self.assertTrue(self.exists(leg.USER_RULE))
        self.assertEqual(_read(os.path.join(self.run_dir, leg.USER_RULE)),
                         leg.USER_RULE_TEXT)
        cfg = json.loads(_read(os.path.join(self.run_dir, '.mcp.json')))
        self.assertIn(leg.USER_SERVER, cfg['mcpServers'])

    def test_the_users_rules_directory_survives_its_emptydir_entry(self):
        """.claude/rules is PLANNED for removal and must stay, because the
        hand-written rule is still in it (a bare rmdir on a non-empty dir)."""
        self.go()
        self.assertTrue(self.exists('.claude/rules'))
        self.assertTrue(self.exists(leg.USER_RULE))
        self.assertStepOk('generated_removed')
        self.assertIn('kept dirs', self.step('generated_removed')['detail'])

    def test_the_skills_tree_that_empties_is_gone(self):
        self.go()
        self.assertFalse(self.exists('.claude/skills'))

    def test_externalized_files_and_the_toe_survive(self):
        self.go()
        for rel in ('externalized/comp.tdxn', 'externalized/comp.tox',
                    'externalized/ext.py', 'externalizations.tsv',
                    'smoke_template.toe'):
            self.assertTrue(self.exists(rel), '%s was removed' % rel)


