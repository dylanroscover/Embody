def _hash_tools(tools):
    """Return a stable SHA-1 hash of a tools/list payload.

    The hash is order-independent: the tools are sorted by name before
    serialization, so reordering yields the same hash, but adding,
    removing, or renaming a tool yields a different hash.
    """
    if not tools:
        return hashlib.sha1(b"[]").hexdigest()
    try:
        payload = sorted(
            ({"n": t.get("name", ""), "d": t.get("description", "")}
             for t in tools),
            key=lambda item: item["n"],
        )
    except (TypeError, AttributeError):
        return hashlib.sha1(b"[]").hexdigest()
    blob = json.dumps(payload, sort_keys=True, separators=(",", ":"))
    return hashlib.sha1(blob.encode("utf-8")).hexdigest()


def fetch_tools_list(url, timeout=FETCH_TOOLS_TIMEOUT_S):
    """One-shot forward of a ``tools/list`` JSON-RPC request.

    Returns a list of tool dicts on success, or ``None`` on any failure
    (network error, non-OK HTTP, malformed JSON-RPC, unexpected shape).
    Used by the reconciler to refresh the cached tool list after a
    backend transition.
    """
    msg = {"jsonrpc": "2.0", "id": "bridge-tools-list", "method": "tools/list"}
    try:
        resp = forward_to_http(url, msg, timeout=timeout)
    except Exception:
        return None
    if not isinstance(resp, dict):
        return None
    result = resp.get("result")
    if not isinstance(result, dict):
        return None
    tools = result.get("tools")
    if not isinstance(tools, list):
        return None
    return tools


def ping_backend_mcp(url, timeout=BACKEND_PING_TIMEOUT_S):
    """Ping the backend via MCP ``ping`` method.

    Returns True if the backend returned any JSON-RPC response (including
    ``-32601 method not found``, which still indicates the server is up),
    False on any network error.
    """
    if not url:
        return False
    msg = {"jsonrpc": "2.0", "id": "bridge-ping", "method": "ping"}
    try:
        resp = forward_to_http(url, msg, timeout=timeout)
    except Exception:
        return False
    return isinstance(resp, dict) and ("result" in resp or "error" in resp)


def reconcile(state, on_tools_change, *, heartbeat):
    """Run one reconciliation pass against ``state``.

    Phase 1 (every tick, UNCONDITIONAL): re-read ``envoy.json`` when its
    mtime changes, compare the resolved active port against ``state.url``,
    and switch URL immediately on any drift -- regardless of whether the
    current connection still appears healthy.  This is the fix for the
    dominant failure mode where a user opens a new TD instance mid-session
    and the bridge silently stays pinned to the old one.

    Phase 2 (every heartbeat tick, or immediately after a URL switch):
    ping the backend to detect connection state transitions, then on a
    "became connected" transition refresh the cached tool list.  Emits
    ``on_tools_change`` on tool-list hash changes and on disconnect
    transitions (so the client refetches the bridge-only fallback list).
    """
    # --- PHASE 1: Config reconciliation (every tick, unconditional) ---
    with state:
        config_path = state.config_path
        old_mtime = state.config_mtime
        old_url = state.url

    new_url = None
    if config_path and os.path.exists(config_path):
        try:
            mtime = os.path.getmtime(config_path)
        except OSError:
            mtime = old_mtime
        if mtime != old_mtime:
            new_config = load_config(config_path)
            with state:
                pin = state.pinned_instance
                seen_epoch = state.seen_epoch
            # An increased active_epoch is an explicit all-sessions switch
            # command (switch_instance all_sessions=True) -- it overrides
            # this bridge's pin. Ordinary registry churn (a new instance
            # registering, port updates) never does.
            try:
                epoch = int(new_config.get("active_epoch") or 0)
            except (TypeError, ValueError):
                epoch = 0
            if epoch > seen_epoch:
                commanded = new_config.get("active")
                if commanded:
                    log(f"active_epoch {seen_epoch} -> {epoch}: adopting "
                        f"all-sessions switch to '{commanded}'")
                    pin = commanded
            port, pid, resolved_name = _resolve_from_registry(
                new_config, None, pin=pin)
            if pin and resolved_name != pin:
                # Pinned instance vanished from the registry: follow the
                # default LOUDLY but keep the pin -- if the instance
                # re-registers (TD restart, same toe name) we re-attach.
                log(f"WARNING: pinned instance '{pin}' is not in the "
                    f"registry; following default "
                    f"'{resolved_name}' until it returns")
            candidate = f"http://127.0.0.1:{port}/mcp" if port else None
            with state:
                state.config = new_config
                state.config_mtime = mtime
                state.seen_epoch = max(seen_epoch, epoch)
                if pin:
                    state.pinned_instance = pin
                elif resolved_name:
                    # First successful resolution: adopt it as this
                    # bridge's pin so later registry 'active' churn
                    # cannot silently re-target this session.
                    state.pinned_instance = resolved_name
                # Adopt a pid ONLY from OUR pinned instance. When the pin is
                # missing from the registry we deliberately follow the
                # default's URL (logged above) -- but taking its PID too
                # would point crash detection at a foreign project's
                # TouchDesigner. That is the normal post-crash shape, not an
                # edge case: the registry garbage-collects dead-pid rows on
                # every write by any peer, so our crashed instance's row
                # disappears and this branch is exactly where we land.
                # ...but a RENAME is not a foreign instance. Every release
                # bumps the .toe filename, so the instance name changes
                # (Embody-6.157 -> Embody-6.159) and the pin goes stale on
                # the very next open. If the resolved instance answers on
                # the port we are already talking to, it IS our instance
                # under a new name -- adopting its pid is correct, and
                # refusing would silently degrade crash detection after
                # every single release. A genuinely foreign instance is on
                # a different port, so this stays closed to it.
                same_endpoint = bool(
                    port and state.url
                    and state.url.endswith(f':{port}/mcp'))
                if pid and (not pin or resolved_name == pin or same_endpoint):
                    state.td_pid = pid
                if resolved_name != state.active_name:
                    state.active_name = resolved_name
                _HEARTBEAT_PIN["name"] = state.pinned_instance
            if candidate and candidate != old_url:
                new_url = candidate

    # If the active instance changed, switch URL immediately.
    # This is the unconditional switch -- doesn't matter if the old URL
    # still responds.  Forces a re-probe on this same tick.
    url_switched = False
    if new_url is not None:
        with state:
            log(f"Active instance changed: {old_url} -> {new_url}")
            state.url = new_url
            state.connected = False
            state.cached_tools = None
            state.cached_tools_hash = None
            url_switched = True

    # --- PHASE 2: Heartbeat (every N config ticks per the dynamic cadence
    # in _current_heartbeat_interval_s, or right after a URL switch so the
    # new backend gets probed immediately) ---
    if not heartbeat and not url_switched:
        return

    with state:
        url = state.url
        was_connected = state.connected
        td_pid = state.td_pid
        cfg_path = state.config_path
        pinned = state.pinned_instance

    is_up = ping_backend_mcp(url) if url else False
    # Image-verified, matching every other TD-pid liveness site (1201,
    # 1289, 1500-1501, 2319): a raw is_process_alive can false-match an
    # OS-RECYCLED pid and suppress genuine crash detection.
    pid_alive = is_td_process_alive(td_pid) if td_pid else False

    became_connected = (not was_connected) and is_up
    became_disconnected = was_connected and not is_up

    # Envoy answers but the pid we track is gone. Two very different
    # causes: TD was relaunched outside the bridge (recoverable), or a
    # FOREIGN instance now holds this port (must NOT be adopted).
    stale_pid_while_up = bool(is_up and td_pid and not pid_alive)

    # Re-resolve OUR pinned instance only. Passing pin=None here would
    # fall through to the registry's global 'active' default and bind this
    # session's tracked pid to a DIFFERENT project's TouchDesigner -- the
    # documented bridge-mistarget failure, and worse than the bug being
    # fixed: is_td_process_alive would then read True for a stranger and
    # genuine crash detection for the pinned TD would be suppressed
    # forever. The canonical resolve in Phase 1 passes the pin; so does this.
    recovered_pid = None
    if stale_pid_while_up:
        try:
            _port, _rpid, _rname = _resolve_from_registry(
                load_config(cfg_path), None, pin=pinned)
            # `_rname` must be a REAL registry instance. Without it, a
            # bridge with no pin (empty/old-format registry) falls through
            # to _resolve_from_registry's find_td_pid() fallback and adopts
            # an arbitrary TouchDesigner on the machine -- exactly what
            # that function's own comment refuses to do.
            if (_rpid and _rpid != td_pid and _rname
                    and (not pinned or _rname == pinned)):
                recovered_pid = _rpid
        except Exception:
            recovered_pid = None

    with state:
        state.connected = is_up
        if is_up:
            state.last_heartbeat_ok = time.time()
            state.last_connected_time = time.time()
            if recovered_pid:
                state.td_pid = recovered_pid
            # Clear ONLY when the live socket is attributable to OUR
            # instance -- either the tracked pid is alive, or we just
            # re-resolved our own pin to a live one. A foreign TD holding
            # the port must never erase a genuine crash flag.
            if pid_alive or recovered_pid:
                # Without this the flag was not merely left over: with
                # td_pid still naming the dead process, the branch below
                # RE-ASSERTED it every heartbeat tick, so get_td_status
                # reported a crash forever after a TD relaunch made
                # outside the bridge (launch_td / restart_td were the only
                # things that ever cleared it).
                state.crash_detected = False
        # UNCHAINED from `is_up` on purpose. Our TD dying IS a crash whether
        # or not something answers the port -- and something usually does
        # within one heartbeat, because Envoy's port scanner hands the
        # just-freed port to the next instance. Written first as an `elif`
        # here, this branch only ran when the ping FAILED, so that race
        # meant the crash was never recorded at all: the mirror image of
        # the stuck-flag bug this release set out to fix. The clear above
        # already ran for the attributable cases, so this cannot undo it.
        if td_pid and not pid_alive and not recovered_pid:
            state.crash_detected = True

    # Log on TRANSITIONS only. An unconditional log here would fire every
    # heartbeat tick for as long as the condition holds -- the same
    # unbounded-repetition failure this release fixes for annotation
    # warnings.
    if recovered_pid:
        log(f"Tracked TD pid {td_pid} is gone but Envoy answers; "
            f"re-resolved to pid {recovered_pid} for pinned instance "
            f"'{pinned}'")
    elif stale_pid_while_up and became_connected:
        log(f"Tracked TD pid {td_pid} is not alive yet Envoy answers on "
            f"{url} -- possible foreign instance holding this port; "
            f"crash state left untouched")

    # --- Proactive TD process discovery ---
    # Detect new TD processes that appeared since the last heartbeat.
    # If new TDs are found, force a config re-read on the next tick so
    # the reconciler picks up any registry changes they may have written.
    current_td_pids = set(find_all_td_pids())
    with state:
        old_pids = state.known_td_pids
        new_pids = current_td_pids - old_pids
        gone_pids = old_pids - current_td_pids
        state.known_td_pids = current_td_pids
        if new_pids:
            state.config_mtime = 0  # Force config re-read next tick
    if new_pids:
        log(f"New TD process(es) detected: {sorted(new_pids)}")
    if gone_pids:
        log(f"TD process(es) exited: {sorted(gone_pids)}")

    notify_changed = False

    if became_connected:
        # Refresh the tool list on a connect transition.  If the hash
        # changed (different Envoy version or tool set), fire list_changed.
        # If identical, this is a silent switch -- no notification.
        new_tools = fetch_tools_list(url)
        if new_tools is not None:
            augmented = list(new_tools) + list(BRIDGE_TOOLS)
            new_hash = _hash_tools(augmented)
            with state:
                old_hash = state.cached_tools_hash
                state.cached_tools = augmented
                state.cached_tools_hash = new_hash
                cp = state.config_path
            save_tools_cache(cp, augmented)
            if old_hash is None or old_hash != new_hash:
                notify_changed = True
            else:
                log("Backend switched but tool list is unchanged; no notify")

    if became_disconnected:
        # On disconnect, invalidate the cache and tell the client to
        # refetch -- they'll get the bridge-only fallback list.
        with state:
            state.cached_tools = None
            state.cached_tools_hash = None
        notify_changed = True

    if notify_changed and on_tools_change is not None:
        try:
            on_tools_change()
        except Exception as e:
            log(f"on_tools_change callback failed: {type(e).__name__}: {e}")


def _current_heartbeat_interval_s(state):
    """Return the fixed heartbeat interval (seconds)."""
    return HEARTBEAT_TICK_S


def start_reconciler(state, on_tools_change):
    """Start the daemon reconciler thread.

    The thread loops forever at ``CONFIG_TICK_S`` resolution, running
    the cheap config-mtime check every tick (Phase 1) and the backend
    heartbeat every ``HEARTBEAT_TICK_S`` seconds (Phase 2).  All
    exceptions inside the loop body are caught and logged -- the thread
    must never die.
    """
    def loop():
        # Force first heartbeat on tick 0 (i.e. after the initial sleep)
        last_heartbeat_at_tick = -10 ** 9
        tick = 0
        while True:
            time.sleep(CONFIG_TICK_S)
            try:
                interval_s = _current_heartbeat_interval_s(state)
                ticks_per_heartbeat = max(1, int(interval_s // CONFIG_TICK_S))
                do_heartbeat = (tick - last_heartbeat_at_tick) >= ticks_per_heartbeat
                reconcile(state, on_tools_change, heartbeat=do_heartbeat)
                if do_heartbeat:
                    with state:
                        convoy_target = (
                            dict(state.convoy_target)
                            if isinstance(state.convoy_target, dict)
                            else None)
                    if convoy_target is not None:
                        _publish_convoy_controller(convoy_target)
                    last_heartbeat_at_tick = tick
                # Touch heartbeat on every tick so peers know we're alive
                _touch_heartbeat(state.config_path)
            except Exception as e:
                # NEVER let an exception kill the reconciler -- log and continue
                log(f"Reconciler error (continuing): "
                    f"{type(e).__name__}: {e}")
            tick += 1

    t = threading.Thread(target=loop, daemon=True, name="envoy-reconciler")
    t.start()
    return t


