def convoy_data_dir():
    """Per-user Convoy state dir on THIS machine, or None.

    Joins with the TARGET platform's separator (ntpath on win32, posixpath
    elsewhere), matching convoy_platform.data_dir. At runtime sys.platform
    is the host, so this is just the right separator; the explicit choice
    also lets a foreign-platform test validate the real path SHAPE rather
    than silently getting host-flavored separators (the failure a macOS CI
    run caught one layer down)."""
    import ntpath
    import posixpath
    try:
        join = ntpath.join if sys.platform == "win32" else posixpath.join
        home = os.path.expanduser("~")
        if sys.platform == "win32":
            base = os.environ.get("LOCALAPPDATA") or join(
                home, "AppData", "Local")
            return join(base, CONVOY_APP_DIR_WIN)
        if sys.platform == "darwin":
            return join(home, "Library", "Application Support",
                        CONVOY_APP_DIR_WIN)
        base = os.environ.get("XDG_STATE_HOME") or join(
            home, ".local", "state")
        return join(base, CONVOY_APP_DIR_POSIX)
    except Exception:
        return None


def _read_convoy_portfile(data_dir):
    """Parse the host-app portfile, or None if absent/corrupt."""
    try:
        with open(os.path.join(data_dir, CONVOY_PORTFILE),
                  "r", encoding="utf-8") as f:
            data = json.load(f)
        if isinstance(data, dict) and data.get("port"):
            return data
    except (OSError, ValueError):
        pass
    return None


def _read_convoy_token(data_dir):
    """Read and validate the local host IPC token, or return None."""
    try:
        with open(os.path.join(data_dir, CONVOY_TOKEN_FILE),
                  "r", encoding="utf-8") as f:
            raw = f.read(66)
        if len(raw) > 65:  # 64 hex characters plus the installed newline
            return None
        token = raw.strip()
        if len(token) != 64:
            return None
        int(token, 16)
        return token
    except (OSError, ValueError):
        return None


def _convoy_health_host_id(port):
    """GET the host app's UNAUTHENTICATED /health and return the host_id it
    reports, or None if unreachable. No token is sent -- identity is
    confirmed before any credential would be."""
    try:
        req = urllib.request.Request(
            "http://127.0.0.1:%d/health" % int(port))
        with urllib.request.urlopen(
                req, timeout=CONVOY_HEALTH_TIMEOUT_S) as resp:
            raw = resp.read(CONVOY_HEALTH_MAX_BODY_BYTES + 1)
        if len(raw) > CONVOY_HEALTH_MAX_BODY_BYTES:
            return None
        data = json.loads(raw.decode("utf-8"),
                          parse_constant=_convoy_reject_json_constant)
        host_id = data.get("host_id") if isinstance(data, dict) else None
        return host_id if isinstance(host_id, str) and host_id else None
    except Exception:
        return None


def probe_convoy_host():
    """Locate the local Convoy host app. Returns a dict, NEVER raises:
    {"convoy": "running"|"absent"|"stale", "detail": str, ...}. Reports
    presence only -- routing is unaffected. The whole body is guarded
    because this runs on the bridge STARTUP path and from a meta-tool
    call: a probe fault must degrade to 'behave as if Convoy is absent'
    (direct Envoy), never crash the bridge or the tool call."""
    try:
        data_dir = convoy_data_dir()
        result = {"data_dir": data_dir}
        raw = _read_convoy_portfile(data_dir) if data_dir else None
        if raw is None:
            result["convoy"] = "absent"
            result["detail"] = ("no Convoy host app on this machine; "
                                "using direct Envoy")
            return result
        try:
            pid = int(raw.get("pid"))
        except (TypeError, ValueError):
            pid = 0     # a corrupt/missing pid is unverifiable -> stale
        if pid <= 0 or not is_process_alive(pid):
            result["convoy"] = "stale"
            result["detail"] = ("host-app portfile is stale (writer not "
                                "alive); using direct Envoy")
            return result
        expected = raw.get("host_id")
        # Presence probing never reads the IPC token. Relay calls perform
        # this same health check, require a portfile-pinned identity, fix the
        # destination to literal loopback, and only then read the token.
        confirmed = _convoy_health_host_id(raw.get("port"))
        if confirmed is None:
            result["convoy"] = "stale"
            result["detail"] = ("a process holds the host port but did not "
                                "answer /health; using direct Envoy")
            return result
        if expected and confirmed != expected:
            result["convoy"] = "stale"
            result["detail"] = ("the process on the host port identifies "
                                "as %r, not the expected %r (recycled "
                                "port); using direct Envoy"
                                % (confirmed, expected))
            return result
        result["convoy"] = "running"
        result["host_id"] = confirmed
        result["port"] = raw.get("port")
        result["identity_confirmed"] = bool(expected)
        if expected:
            result["detail"] = (
                "Convoy host app present. Explicit convoy_* tools can use "
                "its authenticated relay surface; ordinary Envoy tools "
                "retain their local target.")
        else:
            # Keep the legacy status probe compatible, but do not let its
            # unpinned result authorize disclosure of the local IPC token.
            result["detail"] = (
                "Convoy host app present, but its legacy portfile has no "
                "host_id; restart/update the host before using relay tools.")
        return result
    except Exception as e:
        return {"convoy": "absent",
                "detail": "probe error (%s); using direct Envoy" % e}


def convoy_host_call(method, path, payload=None, timeout=None):
    """Call one authenticated LOOPBACK host route; always return a dict.

    Identity is confirmed through the unauthenticated health route before
    the token is read or transmitted.  The URL is constructed here from a
    numeric port and the literal loopback address, so host state can never
    redirect the bearer token off-machine.
    """
    # Validate the route BEFORE probing or reading a credential.  In
    # particular, ``@peer`` or ``//peer`` appended to an HTTP origin can
    # change URL authority under RFC parsing.  Callers are internal today,
    # but this invariant keeps a future route parameter from turning the
    # host token into an off-machine Authorization header.
    if method not in ("GET", "POST") or not isinstance(path, str):
        return {"ok": False, "reason": "convoy_bridge_invalid_request",
                "detail": "method/path is not an allowed host request"}
    try:
        parsed = urllib.parse.urlsplit(path)
    except (TypeError, ValueError):
        return {"ok": False, "reason": "convoy_bridge_invalid_request",
                "detail": "Convoy host route is not a valid relative path"}
    if (parsed.scheme or parsed.netloc or parsed.fragment
            or not parsed.path.startswith("/")
            or "\r" in path or "\n" in path):
        return {"ok": False, "reason": "convoy_bridge_invalid_request",
                "detail": "Convoy host route must be a relative path"}
    if payload is not None and not isinstance(payload, dict):
        return {"ok": False, "reason": "convoy_bridge_invalid_request",
                "detail": "Convoy host payload must be an object"}
    if timeout is not None and (
            isinstance(timeout, bool) or not isinstance(timeout, (int, float))
            or not math.isfinite(float(timeout)) or float(timeout) <= 0):
        return {"ok": False, "reason": "convoy_bridge_invalid_request",
                "detail": "Convoy host timeout must be positive and finite"}

    probe = probe_convoy_host()
    if probe.get("convoy") != "running":
        return {"ok": False,
                "reason": "convoy_host_%s" % probe.get("convoy", "absent"),
                "detail": probe.get("detail", "Convoy host unavailable")}
    if probe.get("identity_confirmed") is not True:
        return {"ok": False, "reason": "convoy_host_identity_unverified",
                "detail": "the Convoy portfile did not pin the health "
                          "response to an expected host_id"}
    try:
        port = int(probe.get("port"))
        if not (1 <= port <= 65535):
            raise ValueError("port out of range")
    except (TypeError, ValueError) as e:
        return {"ok": False, "reason": "convoy_host_error",
                "detail": "%s: %s" % (type(e).__name__, e)}

    # Only after health identity AND the literal-loopback destination have
    # been fixed do we read the bearer token.
    data_dir = probe.get("data_dir")
    token = _read_convoy_token(data_dir) if data_dir else None
    if token is None:
        return {"ok": False, "reason": "convoy_token_unreadable",
                "detail": "the local Convoy IPC token is unavailable"}
    try:
        url = "http://127.0.0.1:%d%s" % (port, path)
        body = (json.dumps(payload or {}, allow_nan=False).encode("utf-8")
                if method == "POST" else None)
        headers = {"Accept": "application/json",
                   "X-Convoy-Host-Token": token}
        if body is not None:
            headers["Content-Type"] = "application/json"
        req = urllib.request.Request(url, data=body, headers=headers,
                                     method=method)
        try:
            with urllib.request.urlopen(
                    req, timeout=(float(timeout) if timeout is not None
                                  else CONVOY_HOST_TIMEOUT_S)) as resp:
                status = getattr(resp, "status", 200)
                raw = resp.read(CONVOY_HOST_MAX_BODY_BYTES + 1)
        except urllib.error.HTTPError as e:
            status = e.code
            raw = e.read(CONVOY_HOST_MAX_BODY_BYTES + 1)
        if len(raw) > CONVOY_HOST_MAX_BODY_BYTES:
            return {"ok": False, "reason": "convoy_host_response_too_large",
                    "detail": "local Convoy host response exceeded %d bytes"
                              % CONVOY_HOST_MAX_BODY_BYTES}
        result = json.loads(raw.decode("utf-8"),
                            parse_constant=_convoy_reject_json_constant)
        if not isinstance(result, dict):
            raise ValueError("host response is not an object")
        result["http_status"] = status
        return result
    except (OSError, ValueError, TypeError, urllib.error.URLError,
            RecursionError) as e:
        return {"ok": False, "reason": "convoy_host_error",
                "detail": "%s: %s" % (type(e).__name__, e)}


def _convoy_invalid_arguments(detail):
    return {"ok": False, "reason": "invalid_arguments", "detail": detail}


def _convoy_reject_json_constant(name):
    raise ValueError("%s is not permitted in a Convoy response" % name)


def _convoy_required_text(params, names):
    """Return the first invalid required field, or None.

    MCP clients normally enforce the JSON schemas, but the bridge is also a
    process boundary.  Rejecting locally ensures a malformed call can never
    lose its explicit target and accidentally acquire some future default.
    """
    if not isinstance(params, dict):
        return "arguments must be an object"
    for name in names:
        value = params.get(name)
        if not isinstance(value, str) or not value.strip():
            return "%s must be a non-empty string" % name
    return None


def _convoy_batch_digest(value):
    """Return a stable digest for JSON-safe batch identity material."""
    raw = json.dumps(
        value, sort_keys=True, separators=(",", ":"), ensure_ascii=False,
        allow_nan=False).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()


def _convoy_batch_target_key(batch_key, target):
    """Derive one stable, target-scoped delivery key.

    The target's durable idempotency marker additionally binds this key to
    the operation, arguments, expected runtime, origin, and controller. The
    derived key intentionally does not change with those fields: if a caller
    reuses ``batch_key`` for different work, the existing marker can detect
    and refuse that content conflict instead of creating a second delivery.
    """
    material = {
        "batch_idempotency_key": batch_key,
        "target_host_id": target["target_host_id"],
        "convoy_id": target["convoy_id"],
        "target_node_id": target["target_node_id"],
    }
    return "cb1_" + _convoy_batch_digest(material)


def _convoy_selected_call_key(target, name, arguments):
    """Derive one stable delivery key for a transparently-routed ordinary tool.

    Ordinary Envoy tools expose no idempotency_key parameter, so without this
    every retry of a pinned mutating call (import_network, delete_op, ...) minted
    a fresh uuid4 and the target's content-binding guard could never recognise
    the repeat -- a timed-out-but-delivered call re-run by the agent executed
    twice.  Binding the key to the exact selection, tool name, and a canonical
    digest of the arguments (the same digest shape _convoy_batch_target_key
    uses) makes an identical retry reconcile to the existing durable job, while
    any change to the work digests to a different key.  Returns None if the
    arguments are not canonically serialisable, so the caller falls back to the
    per-call uuid rather than crashing the relay.
    """
    try:
        arguments_digest = _convoy_batch_digest(arguments)
    except (TypeError, ValueError):
        return None
    material = {
        "target_host_id": target["target_host_id"],
        "convoy_id": target["convoy_id"],
        "target_node_id": target["target_node_id"],
        "expected_runtime_id": target.get("expected_runtime_id"),
        "operation": name,
        "arguments_digest": arguments_digest,
    }
    return "cs1_" + _convoy_batch_digest(material)


def _convoy_native_batch_success(relay, expected_count):
    """Classify a terminal relay's native Envoy batch result fail-closed."""
    job = relay.get("job") if isinstance(relay, dict) else None
    if not isinstance(job, dict):
        return None
    state = job.get("state")
    if state not in _CONVOY_TERMINAL_STATES:
        return None
    if state != "succeeded":
        return False
    result = job.get("result")
    if not isinstance(result, dict) or result.get("success") is not True:
        return False
    children = result.get("results")
    count = result.get("count")
    if (not isinstance(children, list)
            or isinstance(count, bool) or not isinstance(count, int)
            or count != len(children) or count != expected_count):
        return False
    return all(isinstance(child, dict) and "error" not in child
               for child in children)


def _convoy_local_scope(result, probe=None):
    """Decorate an honest local-host-only management response."""
    result = dict(result) if isinstance(result, dict) else {
        "ok": False, "reason": "convoy_host_bad_response"}
    result["scope"] = "local_host"
    result["remote_supported"] = False
    result["wakes_touchdesigner"] = False
    if isinstance(probe, dict) and probe.get("host_id"):
        result.setdefault("host_id", probe["host_id"])
    return result


def _convoy_probe_refusal(probe):
    state = (probe.get("convoy", "absent")
             if isinstance(probe, dict) else "absent")
    return _convoy_local_scope({
        "ok": False,
        "reason": "convoy_host_%s" % state,
        "detail": (probe.get("detail", "Convoy host unavailable")
                   if isinstance(probe, dict)
                   else "Convoy host unavailable"),
    }, probe)


def _convoy_add_provenance(result, body, include_operation=False):
    """Attach the exact address the bridge submitted, never a fallback."""
    result = dict(result) if isinstance(result, dict) else {
        "ok": False, "reason": "convoy_host_bad_response"}
    for name in ("target_host_id", "convoy_id", "target_node_id",
                 "delivery_id", "idempotency_key", "controller_id"):
        if body.get(name) is not None:
            result[name] = body[name]
    if include_operation:
        result["operation"] = body.get("operation")
    return result


def handle_convoy_status(params):
    if not isinstance(params, dict):
        return _convoy_invalid_arguments("arguments must be an object")
    probe = probe_convoy_host()
    result = dict(probe)
    result["scope"] = "local_host"
    result["wakes_touchdesigner"] = False
    if probe.get("convoy") != "running":
        return result
    # The authenticated status adds realm/peer/queue facts to the cheap
    # presence probe. Keep it nested so similarly named probe fields cannot
    # be overwritten by a future host status version.
    result["host_status"] = convoy_host_call("GET", "/status")
    return result


def handle_convoy_list_nodes(params):
    if not isinstance(params, dict):
        return _convoy_invalid_arguments("arguments must be an object")
    convoy_id = params.get("convoy_id")
    if convoy_id is not None and (
            not isinstance(convoy_id, str) or not convoy_id.strip()):
        return _convoy_invalid_arguments(
            "convoy_id must be a non-empty string when supplied")
    suffix = ("?convoy_id=" + urllib.parse.quote(convoy_id, safe="")
              if convoy_id is not None else "")
    # No compatibility fallback to /nodes: returning only local nodes when
    # the network route is unavailable would make an incomplete mesh look
    # authoritative.  The named host error is the honest result.
    result = convoy_host_call("GET", "/network/nodes" + suffix)
    result = dict(result) if isinstance(result, dict) else {
        "ok": False, "reason": "convoy_host_bad_response"}
    result["wakes_touchdesigner"] = False
    return result


def _convoy_pin_snapshot(state):
    """Return this session's active Convoy routing pin, or None.

    The local meta-tools (switch_instance, get_td_status, launch_td,
    restart_td) act on the LOCAL TouchDesigner process, but while a pin is set
    every ORDINARY tool call is transparently relayed to the pinned remote
    node.  Surfacing the pin keeps that split visible so an agent never assumes
    an ordinary mutating call (delete_op, import_network) ran locally.
    """
    if state is None:
        return None
    with state:
        return (dict(state.convoy_target)
                if isinstance(state.convoy_target, dict) else None)


def _convoy_selection_view(state):
    with state:
        selected = (dict(state.convoy_target)
                    if isinstance(state.convoy_target, dict) else None)
        active_name = state.active_name
    if selected is None:
        return {
            "ok": True,
            "routing": "direct_local",
            "selected_node": None,
            "local_instance": active_name,
            "wakes_touchdesigner": False,
        }
    return {
        "ok": True,
        "routing": "convoy",
        "selected_node": selected,
        "wakes_touchdesigner": False,
    }


def _publish_convoy_controller(target, clear_selected=False):
    """Best-effort controller heartbeat to the host owning ``target``."""
    if not isinstance(target, dict):
        return None
    required = ("target_host_id", "convoy_id")
    if not all(isinstance(target.get(name), str) and target.get(name)
               for name in required):
        return None
    body = {
        "target_host_id": target["target_host_id"],
        "convoy_id": target["convoy_id"],
        "controller_id": _CONVOY_CONTROLLER_ID,
        "label": "Envoy bridge PID %s" % os.getpid(),
        "clear_selected": bool(clear_selected),
    }
    node_id = target.get("target_node_id")
    if not clear_selected and isinstance(node_id, str) and node_id:
        body["selected_node_id"] = node_id
    return convoy_host_call(
        "POST", "/relay/heartbeat", body,
        timeout=min(3.0, CONVOY_HOST_TIMEOUT_S))


def handle_convoy_select_node(params, state):
    """Set/query this bridge process's exact Convoy routing pin."""
    if not isinstance(params, dict):
        return _convoy_invalid_arguments("arguments must be an object")
    clear = params.get("clear", False)
    if not isinstance(clear, bool):
        return _convoy_invalid_arguments("clear must be true or false")
    address_fields = ("target_host_id", "convoy_id", "target_node_id")
    supplied = [name for name in address_fields if params.get(name) is not None]
    if clear:
        if supplied or params.get("expected_runtime_id") is not None:
            return _convoy_invalid_arguments(
                "clear cannot be combined with a Convoy target")
        with state:
            previous = (dict(state.convoy_target)
                        if isinstance(state.convoy_target, dict) else None)
            state.convoy_target = None
        result = _convoy_selection_view(state)
        result["previous_node"] = previous
        if previous is not None:
            result["controller_heartbeat"] = _publish_convoy_controller(
                previous, clear_selected=True)
        return result
    if not supplied and params.get("expected_runtime_id") is None:
        return _convoy_selection_view(state)
    invalid = _convoy_required_text(params, address_fields)
    if invalid:
        return _convoy_invalid_arguments(invalid)
    expected_runtime_id = params.get("expected_runtime_id")
    if expected_runtime_id is not None and (
            not isinstance(expected_runtime_id, str)
            or not expected_runtime_id.strip()):
        return _convoy_invalid_arguments(
            "expected_runtime_id must be a non-empty string when supplied")

    directory = handle_convoy_list_nodes({"convoy_id": params["convoy_id"]})
    if not directory.get("ok"):
        directory["selection_unchanged"] = True
        return directory
    rows = directory.get("nodes")
    if not isinstance(rows, list):
        return {
            "ok": False,
            "reason": "convoy_host_bad_response",
            "detail": "network node response omitted a nodes list",
            "selection_unchanged": True,
            "wakes_touchdesigner": False,
        }
    matches = [row for row in rows if isinstance(row, dict)
               and row.get("host_id") == params["target_host_id"]
               and row.get("convoy_id") == params["convoy_id"]
               and row.get("node_id") == params["target_node_id"]]
    if len(matches) != 1:
        return {
            "ok": False,
            "reason": ("target_not_found" if not matches
                       else "target_ambiguous"),
            "detail": "the exact Convoy host/node address is not uniquely known",
            "target_host_id": params["target_host_id"],
            "convoy_id": params["convoy_id"],
            "target_node_id": params["target_node_id"],
            "selection_unchanged": True,
            "wakes_touchdesigner": False,
        }
    row = matches[0]
    runtime_id = row.get("runtime_id")
    if expected_runtime_id is not None:
        if not isinstance(runtime_id, str) or not runtime_id:
            return {
                "ok": False, "reason": "runtime_unverifiable",
                "detail": "the selected node has no advertised runtime",
                "selection_unchanged": True,
                "wakes_touchdesigner": False,
            }
        if runtime_id != expected_runtime_id:
            return {
                "ok": False, "reason": "runtime_changed",
                "detail": "the selected node's runtime does not match",
                "expected_runtime_id": expected_runtime_id,
                "current_runtime_id": runtime_id,
                "selection_unchanged": True,
                "wakes_touchdesigner": False,
            }
    selected = {
        "target_host_id": params["target_host_id"],
        "convoy_id": params["convoy_id"],
        "target_node_id": params["target_node_id"],
        "expected_runtime_id": (expected_runtime_id or runtime_id),
        "node_name": row.get("node_name"),
        "hostname": row.get("hostname"),
        "toe_name": row.get("toe_name"),
        "status": row.get("status"),
        "online": row.get("online"),
        "embody_version": row.get("embody_version"),
        "touchdesigner_version": row.get("touchdesigner_version"),
    }
    selected = {key: value for key, value in selected.items()
                if value is not None}
    with state:
        previous = (dict(state.convoy_target)
                    if isinstance(state.convoy_target, dict) else None)
        state.convoy_target = selected
    if previous is not None and (
            previous.get("target_host_id"), previous.get("convoy_id"),
            previous.get("target_node_id")) != (
                selected.get("target_host_id"), selected.get("convoy_id"),
                selected.get("target_node_id")):
        _publish_convoy_controller(previous, clear_selected=True)
    result = _convoy_selection_view(state)
    result["controller_heartbeat"] = _publish_convoy_controller(selected)
    return result


def handle_convoy_list_controllers(params):
    """Read the host-federated controller view without touching TD."""
    if not isinstance(params, dict):
        return _convoy_invalid_arguments("arguments must be an object")
    for name in ("convoy_id", "host_id", "node_id"):
        value = params.get(name)
        if value is not None and (
                not isinstance(value, str) or not value.strip()):
            return _convoy_invalid_arguments(
                "%s must be a non-empty string when supplied" % name)

    query = urllib.parse.urlencode({name: params[name]
                                    for name in ("convoy_id", "host_id",
                                                 "node_id")
                                    if params.get(name) is not None})
    path = "/network/controllers" + (("?" + query) if query else "")
    result = convoy_host_call("GET", path)
    result = dict(result) if isinstance(result, dict) else {
        "ok": False, "reason": "convoy_host_bad_response"}
    result["wakes_touchdesigner"] = False
    if not result.get("ok"):
        return result
    controllers = result.get("controllers")
    if not isinstance(controllers, list):
        result.update({
            "ok": False,
            "reason": "convoy_host_bad_response",
            "detail": "controller response omitted a controllers list",
        })
    return result


def handle_convoy_owlette(params):
    """One compact, loopback-only facade over the published Owlette API."""
    if not isinstance(params, dict):
        return _convoy_invalid_arguments("arguments must be an object")
    action = params.get("action", "capabilities")
    allowed = {
        "capabilities", "list_sites", "get_site", "list_machines",
        "get_machine", "command_status", "submit_command",
    }
    if action not in allowed:
        return _convoy_invalid_arguments("action is not supported")
    required = {
        "get_machine": ("site_id", "machine_id"),
        "command_status": ("site_id", "machine_id", "command_id"),
        "submit_command": ("site_id", "machine_id", "command_type",
                           "idempotency_key"),
    }.get(action, ())
    invalid = _convoy_required_text(params, required)
    if invalid:
        return _convoy_invalid_arguments(invalid)
    for name in ("site_id", "machine_id", "command_id", "command_type",
                 "idempotency_key"):
        value = params.get(name)
        if value is not None and (
                not isinstance(value, str) or not value.strip()):
            return _convoy_invalid_arguments(
                "%s must be non-empty text when supplied" % name)
    if params.get("command_type") == "mcp_tool_call":
        return {
            "ok": False, "reason": "owlette_tunnel_forbidden",
            "detail": "mcp_tool_call is not an approved Convoy/Owlette bridge",
            "wakes_touchdesigner": False,
        }
    command_params = params.get("params", {})
    if not isinstance(command_params, dict):
        return _convoy_invalid_arguments("params must be an object")
    timeout_seconds = params.get("timeout_seconds", 60)
    if (isinstance(timeout_seconds, bool)
            or not isinstance(timeout_seconds, int)
            or not 1 <= timeout_seconds <= 600):
        return _convoy_invalid_arguments(
            "timeout_seconds must be an integer from 1 through 600")
    body = {"action": action}
    for name in ("site_id", "machine_id", "command_id", "command_type",
                 "idempotency_key"):
        if params.get(name) is not None:
            body[name] = params[name]
    if action == "submit_command":
        body["params"] = command_params
        body["timeout_seconds"] = timeout_seconds
    result = convoy_host_call("POST", "/owlette", body, timeout=35.0)
    result = dict(result) if isinstance(result, dict) else {
        "ok": False, "reason": "convoy_host_bad_response"}
    result["wakes_touchdesigner"] = False
    return result


def handle_convoy_get_job(params):
    invalid = _convoy_required_text(
        params, ("target_host_id", "convoy_id", "delivery_id"))
    if invalid:
        return _convoy_invalid_arguments(invalid)
    since = params.get("since")
    if since is not None and (
            isinstance(since, bool) or not isinstance(since, (int, float))
            or not math.isfinite(float(since))):
        return _convoy_invalid_arguments("since must be a finite number")
    body = {name: params.get(name) for name in (
        "target_host_id", "convoy_id", "delivery_id", "since")
            if params.get(name) is not None}
    result = convoy_host_call("POST", "/relay/job", body)
    result = _convoy_add_provenance(result, body)
    result["wakes_touchdesigner"] = False
    return result


def handle_convoy_ack_job(params):
    """Idempotently acknowledge one terminal delivery at its owning host."""
    invalid = _convoy_required_text(
        params, ("target_host_id", "convoy_id", "delivery_id"))
    if invalid:
        return _convoy_invalid_arguments(invalid)
    delivery_id = params["delivery_id"]
    if (len(delivery_id) > 256
            or any(ord(char) < 32 or ord(char) == 127
                   for char in delivery_id)):
        return _convoy_invalid_arguments(
            "delivery_id must be bounded printable text")
    body = {name: params[name] for name in (
        "target_host_id", "convoy_id", "delivery_id")}
    result = convoy_host_call("POST", "/relay/ack", body)
    result = _convoy_add_provenance(result, body)
    result["wakes_touchdesigner"] = False
    return result


def _convoy_ack_artifact(reference, target):
    """ACK a job-backed artifact after its bytes have a safe local owner."""
    if not isinstance(reference, dict) or not isinstance(target, dict):
        return None
    delivery_id = reference.get("job_id")
    if (not isinstance(delivery_id, str) or not delivery_id
            or len(delivery_id) > 256
            or any(ord(char) < 32 or ord(char) == 127
                   for char in delivery_id)):
        return None
    values = {name: target.get(name) for name in (
        "target_host_id", "convoy_id")}
    if not all(isinstance(value, str) and value for value in values.values()):
        return None
    values["delivery_id"] = delivery_id
    return handle_convoy_ack_job(values)


def _convoy_release_relay_artifact(materialized, convoy_id):
    """Drop the host-cache handoff after bytes have another safe owner."""
    if not isinstance(materialized, dict):
        return None
    reference = materialized.get("artifact")
    protection_id = materialized.get("relay_protection_id")
    if (not isinstance(reference, dict)
            or not isinstance(reference.get("artifact_id"), str)
            or not isinstance(protection_id, str)):
        return None
    return convoy_host_call("POST", "/relay/artifact/release", {
        "convoy_id": convoy_id,
        "artifact_id": reference["artifact_id"],
        "relay_protection_id": protection_id,
    })


def _convoy_artifact_fields(reference, convoy_id):
    """Validate the small, signed-job-derived metadata before local I/O."""
    if not isinstance(reference, dict):
        raise ValueError("artifact must be an object")
    artifact_id = reference.get("artifact_id")
    digest = reference.get("sha256")
    size = reference.get("size")
    mime_type = reference.get("mime_type", "application/octet-stream")
    if (not isinstance(artifact_id, str)
            or not _CONVOY_ARTIFACT_ID_RE.fullmatch(artifact_id)):
        raise ValueError("artifact has an invalid artifact_id")
    if (not isinstance(digest, str)
            or not _CONVOY_SHA256_RE.fullmatch(digest)
            or artifact_id != "art_" + digest):
        raise ValueError("artifact has an invalid content digest")
    if (isinstance(size, bool) or not isinstance(size, int)
            or not 0 <= size <= CONVOY_ARTIFACT_MAX_BYTES):
        raise ValueError("artifact size is outside the bridge limit")
    if (not isinstance(mime_type, str) or not 1 <= len(mime_type) <= 255
            or "/" not in mime_type
            or any(ord(char) < 32 or ord(char) == 127
                   for char in mime_type)):
        raise ValueError("artifact has an invalid MIME type")
    claimed_convoy = reference.get("convoy_id")
    if claimed_convoy is not None and claimed_convoy != convoy_id:
        raise ValueError("artifact belongs to a different Convoy")
    return {
        "artifact_id": artifact_id,
        "sha256": digest,
        "size": size,
        "mime_type": mime_type,
    }


def _convoy_artifact_route(convoy_id, artifact_id):
    if not isinstance(convoy_id, str) or not convoy_id:
        raise ValueError("convoy_id must be non-empty text")
    try:
        raw = convoy_id.encode("utf-8")
    except UnicodeEncodeError as exc:
        raise ValueError("convoy_id must be valid UTF-8 text") from exc
    if len(raw) > 256:
        raise ValueError("convoy_id is too long")
    segment = base64.urlsafe_b64encode(raw).decode("ascii").rstrip("=")
    return "/artifacts/%s/%s" % (segment, artifact_id)


def _convoy_artifact_suffix(mime_type):
    return {
        "image/jpeg": ".jpg",
        "image/png": ".png",
        "application/json": ".json",
        "text/plain": ".txt",
    }.get(mime_type.lower(), ".bin")


def _convoy_unlink(path):
    if not path:
        return
    try:
        os.unlink(path)
    except (FileNotFoundError, OSError):
        pass
    finally:
        with _CONVOY_ARTIFACT_TEMP_LOCK:
            _CONVOY_ARTIFACT_TEMP_PATHS.discard(path)


def _convoy_track_temp(path):
    with _CONVOY_ARTIFACT_TEMP_LOCK:
        _CONVOY_ARTIFACT_TEMP_PATHS.add(path)


def _cleanup_convoy_artifact_temps():
    """Remove bridge-owned lazy artifacts when the MCP session exits."""
    with _CONVOY_ARTIFACT_TEMP_LOCK:
        paths = tuple(_CONVOY_ARTIFACT_TEMP_PATHS)
        _CONVOY_ARTIFACT_TEMP_PATHS.clear()
    for path in paths:
        try:
            os.unlink(path)
        except (FileNotFoundError, OSError):
            pass


def convoy_host_download_artifact(reference, convoy_id, timeout_s):
    """Stream one already-materialized artifact from loopback and verify it."""
    try:
        fields = _convoy_artifact_fields(reference, convoy_id)
        timeout_s = float(timeout_s)
        if (not math.isfinite(timeout_s) or timeout_s <= 0.0):
            raise ValueError("artifact timeout must be positive and finite")
        route = _convoy_artifact_route(convoy_id, fields["artifact_id"])
    except (TypeError, ValueError) as exc:
        return {"ok": False, "reason": "artifact_invalid",
                "detail": str(exc)}

    probe = probe_convoy_host()
    if probe.get("convoy") != "running":
        return {"ok": False,
                "reason": "convoy_host_%s" % probe.get("convoy", "absent"),
                "detail": probe.get("detail", "Convoy host unavailable")}
    if probe.get("identity_confirmed") is not True:
        return {"ok": False, "reason": "convoy_host_identity_unverified",
                "detail": "the Convoy host identity is not pinned"}
    try:
        port = int(probe.get("port"))
        if not 1 <= port <= 65535:
            raise ValueError("port out of range")
    except (TypeError, ValueError):
        return {"ok": False, "reason": "convoy_host_error",
                "detail": "the Convoy host port is invalid"}
    token = _read_convoy_token(probe.get("data_dir"))
    if token is None:
        return {"ok": False, "reason": "convoy_token_unreadable",
                "detail": "the local Convoy IPC token is unavailable"}

    deadline = time.monotonic() + timeout_s
    connection = None
    local_path = ""
    try:
        connection = http.client.HTTPConnection(
            "127.0.0.1", port, timeout=max(0.001, timeout_s))
        connection.request(
            "GET", route,
            headers={"Accept": "application/octet-stream",
                     "X-Convoy-Host-Token": token,
                     "Connection": "close"})
        response = connection.getresponse()
        if response.status != 200:
            raw = response.read(CONVOY_HOST_MAX_BODY_BYTES + 1)
            if len(raw) > CONVOY_HOST_MAX_BODY_BYTES:
                return {"ok": False,
                        "reason": "convoy_host_response_too_large"}
            try:
                refusal = json.loads(
                    raw.decode("utf-8"),
                    parse_constant=_convoy_reject_json_constant)
            except (UnicodeDecodeError, ValueError, TypeError):
                refusal = None
            if not isinstance(refusal, dict):
                refusal = {"ok": False, "reason": "artifact_download_failed",
                           "detail": "local host returned HTTP %d"
                                     % response.status}
            refusal["http_status"] = response.status
            return refusal

        try:
            response_size = int(response.getheader("Content-Length") or "")
        except ValueError as exc:
            raise ValueError("artifact response omitted a valid length") from exc
        if response_size != fields["size"]:
            raise ValueError("artifact response length did not match metadata")
        if response.getheader("X-Convoy-Artifact-ID") != fields["artifact_id"]:
            raise ValueError("artifact response id did not match metadata")
        if (response.getheader("X-Convoy-Content-SHA256")
                != fields["sha256"]):
            raise ValueError("artifact response hash did not match metadata")

        descriptor, local_path = tempfile.mkstemp(
            prefix="embody_convoy_artifact_",
            suffix=_convoy_artifact_suffix(fields["mime_type"]))
        digest = hashlib.sha256()
        received = 0
        with os.fdopen(descriptor, "wb") as output:
            while received < fields["size"]:
                remaining = deadline - time.monotonic()
                if remaining <= 0.0:
                    raise TimeoutError("artifact download deadline elapsed")
                if connection.sock is not None:
                    connection.sock.settimeout(max(0.001, remaining))
                block = response.read(min(
                    CONVOY_ARTIFACT_CHUNK_BYTES,
                    fields["size"] - received))
                if not block:
                    raise ValueError("artifact response ended early")
                output.write(block)
                digest.update(block)
                received += len(block)
            if response.read(1):
                raise ValueError("artifact response exceeded its declared size")
            output.flush()
            os.fsync(output.fileno())
        if digest.hexdigest() != fields["sha256"]:
            raise ValueError("artifact content failed SHA-256 verification")
        _convoy_track_temp(local_path)
        return {"ok": True, "artifact": reference,
                "local_path": local_path, "bytes": received,
                "verified": True}
    except TimeoutError:
        _convoy_unlink(local_path)
        return {"ok": False, "reason": "artifact_deadline_exceeded",
                "detail": "artifact transfer exceeded its cumulative timeout"}
    except (OSError, ValueError, http.client.HTTPException) as exc:
        _convoy_unlink(local_path)
        return {"ok": False, "reason": "artifact_download_failed",
                "detail": "%s: %s" % (type(exc).__name__, exc)}
    finally:
        if connection is not None:
            try:
                connection.close()
            except OSError:
                pass


def handle_convoy_get_artifact(params, acknowledge=True,
                               release_protection=True):
    """Fetch through the owning peer, then expose only a verified local copy."""
    invalid = _convoy_required_text(
        params, ("target_host_id", "convoy_id", "target_node_id"))
    if invalid:
        return _convoy_invalid_arguments(invalid)
    reference = params.get("artifact")
    try:
        _convoy_artifact_fields(reference, params["convoy_id"])
    except ValueError as exc:
        return _convoy_invalid_arguments(str(exc))
    timeout_s = params.get("timeout_s", 60.0)
    if (isinstance(timeout_s, bool)
            or not isinstance(timeout_s, (int, float))
            or not math.isfinite(float(timeout_s))
            or not 0.1 <= float(timeout_s) <= 3600.0):
        return _convoy_invalid_arguments(
            "timeout_s must be finite and within [0.1, 3600]")

    started = time.monotonic()
    body = {
        "target_host_id": params["target_host_id"],
        "convoy_id": params["convoy_id"],
        "target_node_id": params["target_node_id"],
        "controller_id": _CONVOY_CONTROLLER_ID,
        "artifact": reference,
        "timeout_s": float(timeout_s),
    }
    materialized = convoy_host_call(
        "POST", "/relay/artifact", body, timeout=float(timeout_s))
    materialized = _convoy_add_provenance(materialized, body)
    if materialized.get("ok") is not True:
        materialized["wakes_touchdesigner"] = False
        return materialized
    local_reference = materialized.get("artifact")
    result = None
    keep_protection = False
    try:
        remaining = float(timeout_s) - (time.monotonic() - started)
        if remaining <= 0.0:
            result = {
                "ok": False, "reason": "artifact_deadline_exceeded",
                "detail": "peer materialization consumed the transfer timeout",
                "target_host_id": params["target_host_id"],
                "convoy_id": params["convoy_id"],
                "target_node_id": params["target_node_id"],
                "wakes_touchdesigner": False,
            }
            return result
        result = convoy_host_download_artifact(
            local_reference, params["convoy_id"], remaining)
        result = _convoy_add_provenance(result, body)
        result["wakes_touchdesigner"] = False
        if result.get("ok") is True:
            result["transfer"] = materialized.get("transfer")
            if acknowledge:
                acknowledgement = _convoy_ack_artifact(
                    result.get("artifact"), result)
                if acknowledgement is not None:
                    result["acknowledgement"] = acknowledgement
                    result["acknowledgement_pending"] = (
                        acknowledgement.get("ok") is not True)
            if not release_protection:
                keep_protection = True
                result["_relay_handoff"] = {
                    "artifact": local_reference,
                    "relay_protection_id": materialized.get(
                        "relay_protection_id"),
                }
        return result
    finally:
        if not keep_protection:
            released = _convoy_release_relay_artifact(
                materialized, params["convoy_id"])
            if (isinstance(result, dict) and released is not None
                    and released.get("ok") is not True):
                result["cache_release_pending"] = True
                result["cache_release_reason"] = released.get("reason")


def _convoy_bridge_project_root(state):
    """Derive one real project root only from this bridge's config path.

    The config may live in a subdirectory of ``.embody``, but resolving it
    must still leave a real ``.embody`` ancestor.  Following ``realpath``
    before the ancestor walk makes a lexical symlink escape fail closed.
    """
    if state is None:
        raise ValueError("the Envoy bridge has no project state")
    try:
        with state:
            config_path = state.config_path
    except (AttributeError, TypeError):
        raise ValueError("the Envoy bridge project state is invalid")
    if not isinstance(config_path, str) or not config_path:
        raise ValueError("this Envoy bridge has no project config path")
    try:
        config_path = os.path.realpath(os.path.abspath(config_path))
    except (OSError, TypeError, ValueError) as exc:
        raise ValueError("the Envoy bridge config path is invalid") from exc
    if not os.path.isfile(config_path):
        raise ValueError("the Envoy bridge config file is unavailable")

    current = os.path.dirname(config_path)
    embody_dir = None
    while current:
        if os.path.basename(current) == ".embody":
            embody_dir = current
            break
        parent = os.path.dirname(current)
        if parent == current:
            break
        current = parent
    if embody_dir is None or not os.path.isdir(embody_dir):
        raise ValueError("the Envoy bridge config is not under .embody")
    project_root = os.path.realpath(os.path.dirname(embody_dir))
    if not os.path.isdir(project_root):
        raise ValueError("the Envoy bridge project root is unavailable")
    return project_root


def handle_convoy_save_artifact(params, state):
    """Verify a remote artifact, then explicitly save its cached bytes."""
    invalid = _convoy_required_text(
        params, ("target_host_id", "convoy_id", "target_node_id"))
    if invalid:
        return _convoy_invalid_arguments(invalid)
    reference = params.get("artifact")
    try:
        _convoy_artifact_fields(reference, params["convoy_id"])
    except ValueError as exc:
        return _convoy_invalid_arguments(str(exc))
    filename = params.get("filename")
    if filename is not None:
        if (not isinstance(filename, str) or not filename
                or len(filename.encode("utf-8", "strict")) > 255
                or filename in (".", "..") or "/" in filename
                or "\\" in filename or ":" in filename
                or any(ord(char) < 32 or ord(char) == 127
                       for char in filename)):
            return _convoy_invalid_arguments(
                "filename must be one bounded plain filename")
    overwrite = params.get("overwrite", False)
    if not isinstance(overwrite, bool):
        return _convoy_invalid_arguments("overwrite must be true or false")
    timeout_s = params.get("timeout_s", 60.0)
    if (isinstance(timeout_s, bool)
            or not isinstance(timeout_s, (int, float))
            or not math.isfinite(float(timeout_s))
            or not 0.1 <= float(timeout_s) <= 3600.0):
        return _convoy_invalid_arguments(
            "timeout_s must be finite and within [0.1, 3600]")
    try:
        project_root = _convoy_bridge_project_root(state)
    except ValueError as exc:
        return {"ok": False, "reason": "convoy_project_unavailable",
                "detail": str(exc), "wakes_touchdesigner": False}

    started = time.monotonic()
    materialized = handle_convoy_get_artifact({
        "target_host_id": params["target_host_id"],
        "convoy_id": params["convoy_id"],
        "target_node_id": params["target_node_id"],
        "artifact": reference,
        "timeout_s": float(timeout_s),
    }, acknowledge=False, release_protection=False)
    if materialized.get("ok") is not True:
        return materialized

    relay_handoff = materialized.pop("_relay_handoff", None)

    local_path = materialized.get("local_path")
    result = None
    try:
        remaining = float(timeout_s) - (time.monotonic() - started)
        if remaining <= 0.0:
            result = {
                "ok": False, "reason": "artifact_deadline_exceeded",
                "detail": "artifact verification consumed the save timeout",
                "target_host_id": params["target_host_id"],
                "convoy_id": params["convoy_id"],
                "target_node_id": params["target_node_id"],
                "wakes_touchdesigner": False,
            }
            return result
        body = {
            "target_host_id": params["target_host_id"],
            "convoy_id": params["convoy_id"],
            "target_node_id": params["target_node_id"],
            "project_root": project_root,
            "artifact": materialized.get("artifact"),
            "overwrite": overwrite,
        }
        if filename is not None:
            body["filename"] = filename
        result = convoy_host_call(
            "POST", "/artifact/export", body, timeout=remaining)
        result = _convoy_add_provenance(result, params)
        result["wakes_touchdesigner"] = False
        if result.get("ok") is True:
            acknowledgement = _convoy_ack_artifact(reference, result)
            if acknowledgement is not None:
                result["acknowledgement"] = acknowledgement
                result["acknowledgement_pending"] = (
                    acknowledgement.get("ok") is not True)
        return result
    finally:
        # A save has a durable destination (or a named failure), so its bridge
        # verification copy is never retained as another implicit artifact.
        _convoy_unlink(local_path)
        released = _convoy_release_relay_artifact(
            relay_handoff, params["convoy_id"])
        if (isinstance(result, dict) and released is not None
                and released.get("ok") is not True):
            result["cache_release_pending"] = True
            result["cache_release_reason"] = released.get("reason")


def _convoy_inline_image_valid(mime_type, data):
    mime_type = mime_type.lower()
    if mime_type == "image/png":
        return data.startswith(b"\x89PNG\r\n\x1a\n")
    if mime_type == "image/jpeg":
        return (len(data) >= 4 and data.startswith(b"\xff\xd8\xff")
                and data.endswith(b"\xff\xd9"))
    return False


def convoy_artifact_mcp_content(result):
    """Render a verified image as MCP image content without token-heavy JSON.

    Sanitizes ``result`` IN PLACE: once the bytes are inlined the tempfile is
    unlinked and ``local_path`` dropped from the very dict rendered here.  A
    composite caller that also serializes this same dict in a summary (relay +
    materialization) therefore never advertises a path this function just
    deleted -- previously it took a private copy, so callers embedding the
    original object handed the agent a verified path to a missing file.
    """
    public = result if isinstance(result, dict) else {
        "ok": False, "reason": "artifact_download_failed"}
    blocks = []
    if public.get("ok") is True:
        reference = public.get("artifact")
        path = public.get("local_path")
        try:
            fields = _convoy_artifact_fields(
                reference, public.get("convoy_id"))
            if (fields["mime_type"].lower().startswith("image/")
                    and fields["size"] <= CONVOY_ARTIFACT_IMAGE_MAX_BYTES
                    and isinstance(path, str) and path):
                with open(path, "rb") as source:
                    image_data = source.read(
                        CONVOY_ARTIFACT_IMAGE_MAX_BYTES + 1)
                if (len(image_data) != fields["size"]
                        or hashlib.sha256(image_data).hexdigest()
                        != fields["sha256"]):
                    raise ValueError("local image verification changed")
                if not _convoy_inline_image_valid(
                        fields["mime_type"], image_data):
                    raise ValueError("artifact bytes do not match image MIME")
                blocks.append({
                    "type": "image",
                    "data": base64.b64encode(image_data).decode("ascii"),
                    "mimeType": fields["mime_type"],
                })
                # The MCP block now owns the bytes.  Keeping a second private
                # tempfile for every screenshot would leak disk space across
                # long-running editor sessions, and exposing that local path
                # adds no value once the image is inline.
                _convoy_unlink(path)
                public.pop("local_path", None)
                public["image_inline"] = True
        except (OSError, TypeError, ValueError) as exc:
            public["inline_image_error"] = type(exc).__name__
    text_block = {"type": "text", "text": json.dumps(public, indent=2)}
    return [text_block] + blocks


def materialize_convoy_relay_image(relay, target, timeout_s=60.0):
    """Fetch an image artifact embedded in one successful terminal job."""
    if not isinstance(relay, dict) or not isinstance(target, dict):
        return None
    job = relay.get("job")
    if not isinstance(job, dict) or job.get("state") != "succeeded":
        return None
    payload = job.get("result")
    reference = payload.get("artifact") if isinstance(payload, dict) else None
    mime_type = (reference.get("mime_type")
                 if isinstance(reference, dict) else None)
    if (not isinstance(mime_type, str)
            or mime_type.lower() not in ("image/jpeg", "image/png")):
        return None
    target_host_id = target.get("target_host_id")
    convoy_id = target.get("convoy_id")
    target_node_id = (target.get("target_node_id")
                      or reference.get("node_id"))
    if not all(isinstance(value, str) and value for value in (
            target_host_id, convoy_id, target_node_id)):
        return {"ok": False, "reason": "artifact_invalid",
                "detail": "image artifact omitted exact target provenance"}
    return handle_convoy_get_artifact({
        "target_host_id": target_host_id,
        "convoy_id": convoy_id,
        "target_node_id": target_node_id,
        "artifact": reference,
        "timeout_s": timeout_s,
    })


