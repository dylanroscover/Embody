def _process_cmdline(pid, run=None, proc_root=None):
    """Return the full command line for a PID, or '' if unavailable.

    run/proc_root are injectable so the /proc and ps paths are testable on
    any OS (D-5 Mac-by-construction): pass a fake `run` returning scripted
    `ps` output, or a `proc_root` tmpdir with a synthetic cmdline file.
    Note `-ww`: BSD/macOS ps truncates the args column to the terminal
    width (~80 cols when piped) without it, which silently defeated the
    CEF-helper and port filters on Mac (audit finding).
    """
    run = run or subprocess.run
    try:
        proc_base = proc_root if proc_root else "/proc"
        cmdline_path = os.path.join(proc_base, str(pid), "cmdline")
        if os.path.exists(cmdline_path):
            with open(cmdline_path, "r") as f:
                return f.read().replace(chr(0), " ")
        # macOS / BSD
        result = run(
            ["ps", "-ww", "-p", str(pid), "-o", "args="],
            capture_output=True, text=True, timeout=5,
        )
        return result.stdout
    except (OSError, subprocess.TimeoutExpired, FileNotFoundError):
        return ""


def _is_bridge_process(pid, cmdline=None):
    """Check if a PID is an envoy-bridge process (not actual TouchDesigner).

    The bridge runs TD's bundled Python, so pgrep -f TouchDesigner matches
    it.  Returns True if the process cmdline contains 'envoy-bridge' or
    'envoy_bridge'.  cmdline injectable to avoid a redundant lookup.
    """
    if cmdline is None:
        cmdline = _process_cmdline(pid)
    return "envoy-bridge" in cmdline or "envoy_bridge" in cmdline


# Bundled helper / CEF subprocesses inside TouchDesigner.app share the
# "TouchDesigner" executable name, so `pgrep -f TouchDesigner` matches them
# too.  They are not TD instances -- CEF recycles its GPU/renderer children
# every few seconds, which would otherwise flood the bridge log with phantom
# "new TD process" churn and trigger needless config re-reads.  The Web Render
# helper ("TouchDesigner Web Render.app") is the common one; CEF children also
# carry a "--type=" flag.
_TD_HELPER_MARKERS = ("Web Render", "--type=")


def _is_td_helper_process(pid, cmdline=None):
    """True if PID is a bundled TD helper/CEF subprocess, not a TD instance."""
    if cmdline is None:
        cmdline = _process_cmdline(pid)
    return any(marker in cmdline for marker in _TD_HELPER_MARKERS)


def _process_is_real_td(pid, run=None):
    """True only if PID is a LIVE TouchDesigner *application* process.

    `pgrep -f TouchDesigner` matches any process whose command line merely
    MENTIONS "TouchDesigner" -- e.g. an unrelated shell or AI-CLI job whose
    prompt text references TD -- and also lists defunct/zombie processes.
    Neither is a real TD.  `_process_cmdline()` reads /proc, which does not
    exist on macOS, so the cmdline-based filters above are no-ops there; this
    ps-based check is the reliable cross-platform guard.  Verify the process
    is not a zombie and that its actual executable IS the TD binary.
    """
    run = run or subprocess.run
    try:
        result = run(
            ["ps", "-ww", "-o", "state=", "-o", "comm=", "-p", str(pid)],
            capture_output=True, text=True, timeout=5,
        )
    except (subprocess.TimeoutExpired, FileNotFoundError, ValueError, OSError):
        return False
    if result.returncode != 0:
        return False
    out = result.stdout.strip()
    if not out:
        return False
    parts = out.split(None, 1)
    state = parts[0] if parts else ""
    comm = parts[1].strip() if len(parts) > 1 else ""
    if state.upper().startswith("Z"):
        return False  # defunct/zombie -- cannot be a live TD
    # Real TD binary basename is exactly "TouchDesigner" (app-bundle executable
    # on macOS, bin/TouchDesigner on Linux).  An unrelated process whose argv
    # merely contains "TouchDesigner" has a different executable (zsh, codex,
    # python, ...); bundled helpers are named e.g. "TouchDesigner Web Render".
    return (os.path.basename(comm) == "TouchDesigner"
            or comm.endswith("/Contents/MacOS/TouchDesigner")
            or comm.endswith("/bin/TouchDesigner"))


def find_all_td_pids(platform=None, run=None):
    """Return a list of all running TouchDesigner PIDs.

    Excludes the bridge's own PID and any other envoy-bridge processes,
    which run TD's bundled Python and would otherwise false-match.
    platform/run are injectable so the win32 tasklist path AND the POSIX
    pgrep+filter path both run on any machine (D-5 Mac-by-construction) --
    the five tests that used to self-skip on the Windows dev box now
    execute their real branch everywhere.
    """
    platform = platform or sys.platform
    run = run or subprocess.run
    pids = []
    my_pid = os.getpid()
    if platform == "win32":
        try:
            result = run(
                ["tasklist", "/FI", "IMAGENAME eq TouchDesigner*",
                 "/FO", "CSV", "/NH"],
                capture_output=True, text=True, timeout=5,
            )
            for line in result.stdout.strip().split("\n"):
                if "TouchDesigner" in line:
                    parts = line.strip('"').split('","')
                    if len(parts) >= 2:
                        # Image name is parts[0]. Skip helper processes
                        # (TouchDesignerWebRender.exe matches the
                        # TouchDesigner* filter) -- they are not TD
                        # instances and must never satisfy liveness or
                        # discovery.
                        if "WebRender" in parts[0]:
                            continue
                        try:
                            pids.append(int(parts[1]))
                        except ValueError:
                            pass
        except (subprocess.TimeoutExpired, FileNotFoundError, ValueError):
            pass
        # Windows tasklist filters by image name (TouchDesigner*.exe),
        # so bridge processes (python.exe) won't appear.
        return pids

    # macOS / Linux -- pgrep -f matches cmdline, which catches bridges
    # running TD's bundled Python.  Filter them out.
    try:
        result = run(
            ["pgrep", "-f", "TouchDesigner"],
            capture_output=True, text=True, timeout=5,
        )
        if result.returncode == 0:
            for line in result.stdout.strip().split("\n"):
                line = line.strip()
                if not line:
                    continue
                try:
                    pid = int(line)
                except ValueError:
                    continue
                if pid == my_pid:
                    continue
                # One cmdline read, shared by both string filters.
                cmdline = _process_cmdline(pid, run=run)
                if _is_bridge_process(pid, cmdline=cmdline):
                    continue
                if _is_td_helper_process(pid, cmdline=cmdline):
                    continue
                if not _process_is_real_td(pid, run=run):
                    continue  # unrelated process matching the cmdline, or a zombie
                pids.append(pid)
    except (subprocess.TimeoutExpired, FileNotFoundError, ValueError):
        pass
    return pids


def find_td_pid():
    """Find the PID of a running TouchDesigner process. Returns int or None.

    INSTANCE-BLIND: returns the first TD process on the machine. Use it
    ONLY where no instance identity exists (legacy flat configs, empty
    registry). Anywhere an ACTIVE registered instance is in play, a dead
    registered pid must resolve to None -- adopting a stranger's pid here
    is what made dead instances read as alive on multi-instance machines
    (issue #57 follow-up).
    """
    pids = find_all_td_pids()
    return pids[0] if pids else None


def is_process_alive(pid, platform=None, kill=None):
    """Check if a process is still running.

    platform is injectable (D-5): the existing win32 tests reach this
    through `@patch('envoy_bridge.sys')`, a module-mock pattern that has
    already failed once in a full-suite run (a mocked platform silently
    failed to take and a REAL taskkill escaped to the host). New tests
    pass platform= instead.
    """
    if not pid or pid <= 0:
        return False
    platform = platform or sys.platform
    # kill= exists so injecting platform='darwin' on a Windows host can
    # never reach the REAL os.kill: on Windows os.kill(pid, 0) calls
    # TerminateProcess and would kill the target (the documented
    # TD-killing hazard). Tests inject both.
    kill = kill or os.kill
    if platform == "win32":
        # os.kill(pid, 0) on Windows calls TerminateProcess() -- it KILLS the
        # process instead of checking liveness.  Use OpenProcess(SYNCHRONIZE)
        # which only requires the right to wait on the object.
        try:
            import ctypes
            from ctypes import wintypes
            # PRIVATE kernel32 instance: ctypes.windll.kernel32 is cached
            # process-wide, so setting restype/argtypes on it would mutate
            # prototypes any other code in this process relies on.
            kernel32 = ctypes.WinDLL("kernel32")
            kernel32.OpenProcess.restype = wintypes.HANDLE
            kernel32.OpenProcess.argtypes = [
                wintypes.DWORD, wintypes.BOOL, wintypes.DWORD]
            kernel32.WaitForSingleObject.restype = wintypes.DWORD
            kernel32.WaitForSingleObject.argtypes = [
                wintypes.HANDLE, wintypes.DWORD]
            kernel32.CloseHandle.argtypes = [wintypes.HANDLE]

            SYNCHRONIZE = 0x00100000
            WAIT_OBJECT_0 = 0x00000000
            handle = kernel32.OpenProcess(SYNCHRONIZE, False, pid)
            if not handle:
                return False
            try:
                # OpenProcess SUCCEEDING IS NOT LIVENESS.  A terminated
                # process whose handle is still held open by anything else
                # keeps its process object -- and its PID -- allocated, so
                # OpenProcess keeps succeeding and that pid reads ALIVE
                # forever (measured 2026-07-27 on a dead TD pid).  Here that
                # stranded heartbeat files for exited sessions, which then
                # linger as phantom peers in get_sessions/_peers advisories.
                #
                # A process object is SIGNALED exactly when the process
                # exits, so a zero-timeout wait separates the two cases.
                # Anything but WAIT_OBJECT_0 (including WAIT_FAILED) counts
                # as ALIVE -- not reaping what we could not verify is the
                # safe direction.
                return kernel32.WaitForSingleObject(handle, 0) != WAIT_OBJECT_0
            finally:
                kernel32.CloseHandle(handle)
        except Exception:
            return False
    # Unix: signal 0 is a no-op liveness check
    try:
        kill(pid, 0)
        return True
    except (ProcessLookupError, PermissionError):
        return False
    except OSError:
        return False


def is_td_process_alive(pid):
    """True iff pid is alive AND is an actual TouchDesigner instance.

    is_process_alive() alone is not enough for REGISTRY pids: the OS
    recycles PIDs (aggressively on Windows), so a stale registered pid can
    be alive as some unrelated process -- which made a dead instance read
    as running and launch_td refuse to relaunch it (issue #57 follow-up).
    find_all_td_pids() is image-filtered (and excludes bridges/helpers),
    so membership proves the pid really is TouchDesigner.
    """
    if not is_process_alive(pid):
        return False
    return pid in find_all_td_pids()


