def augment_tools_list(response):
    """Append bridge meta-tools to a tools/list response from TD.

    Idempotent: a response that already carries the bridge tools (a cached
    tools/list re-served within the cache window, or a double augmentation
    on a refresh path) must not accumulate duplicates. This guard existed
    in the disk-fallback copy but was missing from this template -- the
    shipped bridge duplicated meta-tools until 2026-07-16.
    """
    if (response
            and "result" in response
            and "tools" in response["result"]):
        tools = response["result"]["tools"]
        existing = {
            tool.get("name") for tool in tools
            if isinstance(tool, dict)
        }
        tools.extend(
            tool for tool in BRIDGE_TOOLS
            if tool.get("name") not in existing
        )
    return response


def bridge_only_tools_list(request_id):
    """Generate a tools/list response with only bridge meta-tools."""
    return {
        "jsonrpc": "2.0",
        "id": request_id,
        "result": {"tools": list(BRIDGE_TOOLS)},
    }


# ---------------------------------------------------------------------------
# Tool list disk cache -- survives bridge restarts
# ---------------------------------------------------------------------------
# Claude Code caches the tool list from the first tools/list response and
# does NOT refresh it when notifications/tools/list_changed is sent (known
# bug anthropics/claude-code#13646).  To work around this, we persist the
# last-known full tool list (TD tools + bridge meta-tools) to disk.  On
# startup, if Envoy isn't reachable within the quick probe, we return the
# cached list instead of bridge-only tools.

_TOOLS_CACHE_FILENAME = "envoy-tools-cache.json"


def _tools_cache_path(config_path):
    """Return the path to the tools cache file (sibling of envoy.json in .embody/)."""
    if not config_path:
        return None
    embody_dir = os.path.dirname(os.path.abspath(config_path))
    return os.path.join(embody_dir, _TOOLS_CACHE_FILENAME)


def save_tools_cache(config_path, tools):
    """Persist the full tool list to disk.  Best-effort, never raises."""
    path = _tools_cache_path(config_path)
    if not path:
        return
    try:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        atomic_write_json(path, {"tools": tools})
    except Exception:
        pass


def load_tools_cache(config_path):
    """Load the cached tool list from disk.  Returns list or None."""
    path = _tools_cache_path(config_path)
    if not path or not os.path.exists(path):
        return None
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        tools = data.get("tools")
        if isinstance(tools, list) and len(tools) > 0:
            return tools
    except (json.JSONDecodeError, OSError, KeyError):
        pass
    return None


def best_available_tools_list(request_id, config_path):
    """Return the best tools/list response we can without Envoy.

    If a disk cache exists from a previous session, return the cached TD tools
    overlaid with THIS bridge's current meta-tool set.  A cache written by an
    older bridge predates the convoy_* tools (and carries stale meta-tool
    descriptions); serving it verbatim hid every convoy_* tool -- and lied
    about routing -- for a whole TD-closed session, because the MCP client
    caches the first tools/list and ignores tools/list_changed.  Dropping any
    cached copy of a bridge meta-tool and re-augmenting guarantees the current
    definitions win while the cached TD tools survive.  Falls back to
    bridge-only when there is no cache.
    """
    cached = load_tools_cache(config_path)
    if cached:
        td_tools = [
            tool for tool in cached
            if not (isinstance(tool, dict)
                    and tool.get("name") in BRIDGE_TOOL_NAMES)
        ]
        response = {
            "jsonrpc": "2.0",
            "id": request_id,
            "result": {"tools": td_tools},
        }
        augment_tools_list(response)
        tools = response["result"]["tools"]
        log(f"Returning {len(tools)} tools from disk cache "
            "(Envoy not yet reachable)")
        return response
    return bridge_only_tools_list(request_id)


# ---------------------------------------------------------------------------
# HTTP forwarding and connection management
# ---------------------------------------------------------------------------

# Set by main() so a server-pushed tools/list_changed can drop the
# bridge's OWN cached tool list.  Module level because forwarding happens
# on both the main loop and the reconciler thread, and neither path
# carries a state handle down to the frame router.
_tools_cache_invalidator = None

# Both spellings: the MCP method is namespaced, but a server that sends
# the bare name still means the same thing and costs us one refetch.
_LIST_CHANGED_METHODS = (
    "notifications/tools/list_changed",
    "tools/list_changed",
)


def set_tools_cache_invalidator(fn):
    """Register the callback a received tools/list_changed fires (or None)."""
    global _tools_cache_invalidator
    _tools_cache_invalidator = fn


def _invalidate_tools_cache():
    """Fire the registered invalidator.  Best-effort, never breaks a forward."""
    fn = _tools_cache_invalidator
    if fn is None:
        return
    try:
        fn()
    except Exception as e:
        log(f"Tool cache invalidation failed: {type(e).__name__}: {e}")


def deliver_server_message(msg):
    """Write a server-pushed JSON-RPC message straight through to the client.

    Peer of ``notify_stdout``/``send_response``: one JSON object per line
    behind ``_stdout_lock``, so a frame routed off the reconciler thread
    cannot interleave with a response written by the main loop.  The
    cache invalidation runs BEFORE the lock is taken -- nothing may hold
    stdout while reaching for the state lock.
    """
    if not isinstance(msg, dict):
        return
    if msg.get("method") in _LIST_CHANGED_METHODS:
        _invalidate_tools_cache()
    payload = dict(msg)
    payload.setdefault("jsonrpc", "2.0")
    with _stdout_lock:
        try:
            sys.stdout.write(json.dumps(payload) + "\n")
            sys.stdout.flush()
        except (BrokenPipeError, OSError):
            # Client closed stdout -- the main stdin loop discovers the
            # closure on its next iteration.
            pass


def _is_server_pushed(msg, request_id):
    """True when a decoded frame is server-initiated, not our answer.

    JSON-RPC draws the line exactly: a NOTIFICATION carries a ``method``
    and no ``id``; a server-to-client REQUEST carries both.  Neither
    answers the message we posted, so both go to the client and the read
    continues.  Everything else -- a result/error frame, or the bare
    id-less payload a non-streaming server may hand back -- terminates
    the forward, which is what shipped before streaming existed.
    """
    if not isinstance(msg, dict):
        return False
    if not isinstance(msg.get("method"), str):
        return False
    msg_id = msg.get("id")
    if msg_id is None:
        return True
    return msg_id != request_id


class _BodyMirror:
    """Keeps the raw body only while a plain-JSON fallback is still possible.

    A non-streaming Envoy answers with one JSON object and no SSE
    framing, so the whole body has to be reassembled at EOF.  A live
    stream must never be accumulated -- it can run for minutes.
    ``stop()`` fires on the first SSE framing LINE (a field or a comment
    keepalive), not on the first complete frame: a stream of comments, or
    of event/id fields with no data, is just as much a stream and used to
    be recorded forever.  Past ``_MAX_BODY_BYTES`` recording stops on its
    own -- a body that large is not a JSON answer this bridge could hand
    to a parser anyway, and that is the only bound for a peer that is
    neither SSE nor terminated.
    """

    def __init__(self):
        self._parts = []
        self._size = 0
        self.recording = True

    def add(self, chunk):
        if not self.recording:
            return
        self._size += len(chunk)
        if self._size > _MAX_BODY_BYTES:
            self.stop()
            return
        self._parts.append(chunk)

    def stop(self):
        self.recording = False
        self._parts = []

    def body(self):
        return b"".join(self._parts)


# SSE field names are bare; every JSON key is quoted.  That makes a
# framing line unambiguous evidence that the body is a stream, which is
# what tells the mirror to stop recording.
_SSE_FIELDS = ("data", "event", "id", "retry")


def _is_sse_line(line):
    """True when a stripped line is SSE framing (a field or a comment)."""
    if line.startswith(":"):
        return True
    field, sep, _value = line.partition(":")
    return bool(sep) and field in _SSE_FIELDS


class _ReadBudget:
    """Applies BOTH bounds of a forward to the socket, before every read.

    ``deadline`` is the request cap; ``gap`` is the inter-frame
    allowance, unset until a cadence is established and renewed by every
    frame after that (see the constants for why one frame is not a
    cadence).  Each read is issued with the SMALLER of what is left of
    the two, so neither bound can be overrun by the other's slack -- the
    defect where a stream whose last frame landed just before the
    deadline still got a full idle window on top of the cap.  This class
    governs the BODY only; nothing here runs during the status/header
    phase urlopen reads for itself.

    Tightening is best-effort: urllib exposes no handle for a live
    socket, so a response layout we do not recognize simply keeps the
    timeout urlopen set, and the between-reads check still severs at the
    cap.
    """

    def __init__(self, resp, deadline, clock, armed=None):
        self._resp = resp
        self._deadline = deadline
        self._clock = clock
        self._gap = None
        # What urlopen already put on the socket, so an opening read is
        # not re-armed with the value it already has.
        self._armed = armed

    def renew(self, gap):
        """A frame landed: the next gap starts its allowance over."""
        self._gap = gap
        self._armed = None  # Force the re-arm, so a renewal is observable

    def arm(self):
        """Bound the next read.  Raises once the absolute cap is spent."""
        budget = None
        if self._deadline is not None:
            budget = self._deadline - self._clock()
            if budget <= 0:
                raise TimeoutError("Envoy stream exceeded the request cap")
        if self._gap is not None and (budget is None or self._gap < budget):
            budget = self._gap
        if budget is None:
            return
        if self._armed is not None and abs(self._armed - budget) < 0.25:
            # Close enough -- skip the syscall on every single read.
            # ABSOLUTE, not one-sided: ``deadline = clock() + timeout``
            # can round UP at some clock magnitudes, so the first arm's
            # remaining budget lands a few 1e-14 ABOVE the value urlopen
            # already armed.  The one-sided check read that sliver as
            # "needs re-arm" on machines with small monotonic values
            # (fresh-boot CI runners) and skipped it on long-uptime dev
            # boxes -- a machine-dependent spurious settimeout.  Real
            # growth cannot occur here: the deadline is fixed, the clock
            # is monotonic, and renew() resets _armed to force its re-arm.
            return
        if _tighten_read_timeout(self._resp, budget):
            self._armed = budget


def _iter_response_lines(resp, mirror, budget):
    """Yield decoded, stripped lines from ``resp`` the moment each lands.

    ``read1`` returns as soon as ANY bytes are available rather than
    waiting for a full buffer or a newline, so a frame reaches the router
    the instant its newline lands AND the budget is re-checked between
    every read.  That second property is why this is not ``readline``: a
    peer that trickles bytes without ever completing a line keeps
    resetting the per-recv socket timeout, so a blocking readline sat
    inside ONE call -- pinning the stdin dispatch loop -- for as long as
    the trickle lasted, with neither bound applying.

    Lines are stripped, matching the leniency the pre-streaming parser
    had toward padded ``data:`` lines and CRLF.  Bytes are decoded only
    once a line is complete, so a multi-byte character split across two
    reads survives; decode errors are replaced rather than raised, since
    one mangled line must not destroy frames already delivered.
    """
    buf = bytearray()
    while True:
        budget.arm()
        chunk = resp.read1(_READ_CHUNK_BYTES)
        if not chunk:
            break
        mirror.add(chunk)
        buf += chunk
        # Checked on EVERY chunk, not only newline-free ones: gating it on
        # "no newline in this chunk" let a line that finally terminates AT
        # the cap through, and everything below (the bytes() copy, split,
        # decode, strip, partitions) then ran over ~128 MiB uncapped --
        # measured 4x the nominal ceiling in transient allocation.  After a
        # split ``buf`` holds only the trailing partial line, so this
        # measures exactly what it means to: the line being assembled.
        if len(buf) > _MAX_BODY_BYTES:
            raise ConnectionError(
                "Envoy sent an unterminated line past the buffer cap")
        if b"\n" not in chunk:
            continue
        pieces = bytes(buf).split(b"\n")
        buf = bytearray(pieces.pop())
        for piece in pieces:
            line = piece.decode("utf-8", "replace").strip()
            if mirror.recording and _is_sse_line(line):
                mirror.stop()
            yield line
    if buf:
        yield bytes(buf).decode("utf-8", "replace").strip()


def _sse_frames(lines):
    """Yield one ``data`` payload per complete SSE frame from ``lines``.

    Per the SSE wire format a blank line closes a frame, a line starting
    with ":" is a comment (the keepalive servers send to hold a stream
    open), and repeated ``data:`` fields join with newlines.  Fields
    other than data (event, id, retry) are read and dropped -- the bridge
    routes on the JSON-RPC payload, never on the SSE event name.  A
    trailing frame with no closing blank line is still yielded at EOF.
    A frame that never closes is severance, not an excuse to grow.
    """
    data = []
    size = 0
    for line in lines:
        if not line:
            if data:
                yield "\n".join(data)
                data = []
                size = 0
            continue
        if line.startswith(":"):
            continue
        field, sep, value = line.partition(":")
        if not sep:
            continue  # Not a field line at all -- carries nothing we route on
        if value.startswith(" "):
            value = value[1:]
        if field == "data":
            data.append(value)
            size += len(value)
            if size > _MAX_BODY_BYTES:
                raise ConnectionError(
                    "Envoy sent an SSE frame past the buffer cap")
    if data:
        yield "\n".join(data)


def _tighten_read_timeout(resp, seconds):
    """Bound the wait for the next read of a response already in flight.

    urllib exposes no handle for this, so reach through the response's
    file object to the socket underneath.  Best-effort by design: a
    layout we do not recognize simply keeps the original timeout, and the
    absolute cap still bounds the read.  Returns True when it took.
    """
    try:
        resp.fp.raw._sock.settimeout(seconds)
        return True
    except (AttributeError, OSError, TypeError, ValueError):
        return False


def _route_sse_frames(payloads, request_id, deliver, budget=None,
                      idle_timeout=None):
    """Consume SSE payloads; return the one that answers ``request_id``.

    Shared by the incremental reader and the read-to-EOF escape hatch so
    the two can never disagree about what answers a request.  This is the
    whole reason the hatch is not a revert: the pre-streaming line
    scanner returned the first frame it could parse, which -- once a
    server pushes progress -- is a NOTIFICATION delivered to the client
    as its tool result.

    Server-pushed frames go to ``deliver`` and the read continues.  With
    a ``budget``, every pushed frame after the first renews the gap
    allowance; without one (the hatch) there is no live socket to bound.
    """
    pushed = 0
    for payload in payloads:
        payload = payload.strip()
        if not payload:
            continue
        try:
            msg = json.loads(payload)
        except json.JSONDecodeError:
            continue  # Truncated or non-JSON frame -- try the next
        if not _is_server_pushed(msg, request_id):
            return msg
        pushed += 1
        if budget is not None and pushed > 1:
            budget.renew(idle_timeout)
        deliver(msg)
    return None


def _stream_disabled():
    """True when EMBODY_BRIDGE_NO_STREAM asks for the read-to-EOF path."""
    raw = os.environ.get(_STREAM_FALLBACK_ENV) or ""
    return raw.strip().lower() not in ("", "0", "false", "no", "off")


def forward_to_http(url, message, timeout=REQUEST_TIMEOUT_S, *,
                    idle_timeout=None, on_notification=None,
                    clock=time.monotonic):
    """Forward a JSON-RPC message to the Envoy HTTP endpoint.

    Uses a fresh ``urllib.request.urlopen`` per call for simplicity and
    reliability.  The response body is read INCREMENTALLY: every SSE
    ``data:`` frame is routed the moment it lands, so a server-pushed
    notification (progress, tools/list_changed) reaches the client while
    the operation is still running instead of dying in a read-to-EOF
    buffer.  Server-pushed NOTIFICATIONS are what this enables; a
    server-to-client REQUEST is delivered but cannot be answered until
    the forward returns, because the single-threaded stdin dispatch loop
    is parked in here for the life of the stream.

    A request that gets no answer NEVER returns None -- every such exit
    raises, so the main loop replies and flips connectivity instead of
    leaving the client's id unanswered forever.  None means only that
    nothing was owed: the forwarded message carried no ``id``.

    Frames the client must see go out through ``on_notification``
    (default: ``deliver_server_message``, i.e. stdout behind the
    serialization lock).  ``timeout`` caps the forward from the first
    BODY byte -- the status/header phase urlopen reads is bounded
    per-recv only, so a header-dribbling peer can exceed it (pre-existing;
    see the constants).  Passing None or 0 means no cap at all.
    ``idle_timeout`` bounds the silence between frames once a cadence
    exists.  Either breach surfaces as an OSError, exactly like a socket
    timeout, and the reconciler drives recovery.  ``clock`` is injectable
    for tests; never patch time globally.

    A server that answers plain ``application/json`` (a pre-streaming
    Envoy) is handled by the same reader: nothing parses as an SSE frame,
    the mirrored body is decoded whole at EOF, and the shipped result
    comes back unchanged.

    EMBODY_BRIDGE_NO_STREAM reads the whole body first and then runs the
    SAME parser over it.  Batching pushed frames to EOF is not its only
    cost: that path has NO cap, NO idle window, and NO accumulation
    bound, because ``resp.read()`` is one call this code cannot get
    between.  It is bounded by the per-recv socket timeout alone -- the
    pre-streaming semantics, restored whole -- so an operator who flips
    it to escape a hang can have the stdin dispatch loop pinned
    indefinitely by a half-dead peer.  It is a lever for a broken
    PARSER, not for a broken peer.
    """
    data = json.dumps(message).encode("utf-8")
    req = urllib.request.Request(
        url,
        data=data,
        headers={
            "Content-Type": "application/json",
            "Accept": "application/json, text/event-stream",
            "X-Envoy-Session": SESSION_ID,
            "X-Envoy-Label": SESSION_LABEL or f"pid{_MY_PID}",
        },
    )
    request_id = message.get("id") if isinstance(message, dict) else None
    answer_owed = isinstance(message, dict) and "id" in message
    if idle_timeout is None:
        idle_timeout = (SSE_IDLE_WINDOW_S if not timeout
                        else min(timeout, SSE_IDLE_WINDOW_S))
    deadline = clock() + timeout if timeout else None
    deliver = on_notification or deliver_server_message

    resp = urllib.request.urlopen(req, timeout=timeout)
    try:
        if _stream_disabled():
            body_bytes = resp.read()
            lines = [line.strip() for line
                     in body_bytes.decode("utf-8", "replace").split("\n")]
            answer = _route_sse_frames(
                _sse_frames(lines), request_id, deliver)
        else:
            mirror = _BodyMirror()
            budget = _ReadBudget(resp, deadline, clock, armed=timeout)
            answer = _route_sse_frames(
                _sse_frames(_iter_response_lines(resp, mirror, budget)),
                request_id, deliver, budget=budget,
                idle_timeout=idle_timeout)
            # Empty once the body proved to be a stream, so this is the
            # non-streaming path's buffer and nothing else.
            body_bytes = mirror.body()
        if answer is not None:
            return answer

        # Non-streaming server (or a body with no SSE framing at all):
        # decode what we buffered and parse it whole, as shipped.
        #
        # Known and accepted: on THIS path a multi-MB body is materialized
        # several times over (the line buffer, the mirror's chunk list,
        # the bytes() copy, the decoded line, and the string partition()
        # makes), measured at ~2.5x the shipped transient memory and ~3x
        # the wall time on a 5-16 MB body.  It is not a mystery to
        # rediscover: the SSE path is unaffected (the mirror stops at the
        # first framing line) and the real Envoy speaks SSE, where live
        # forwards measured FASTER than shipped.  Only a pre-streaming
        # Envoy returning megabytes pays it, so the compat floor keeps
        # the simple code.
        body = body_bytes.decode("utf-8")
        if body.strip():
            try:
                return json.loads(body)
            except json.JSONDecodeError:
                pass
        if not answer_owed:
            return None  # We posted a notification; no answer was owed
        raise ConnectionError(
            "Envoy closed the response without answering the request")
    except http.client.IncompleteRead as e:
        # A graceful FIN mid-body. http.client raises this instead of an
        # OSError, so untranslated it reaches the main loop's catch-all
        # and reports "Unexpected error" for what is plainly a severed
        # transport -- no reconnect hint, different wording than every
        # other mid-stream cut. One verdict for one failure.
        raise ConnectionError(f"Envoy closed the response mid-body ({e})")
    finally:
        try:
            resp.close()
        except Exception:
            pass


def send_response(response):
    """Write a JSON-RPC response to stdout (STDIO MCP transport).

    Serialized via ``_stdout_lock`` so the reconciler thread's notification
    writes cannot interleave with a response mid-line.
    """
    with _stdout_lock:
        sys.stdout.write(json.dumps(response) + "\n")
        sys.stdout.flush()


def send_error(request_id, code, message):
    """Send a JSON-RPC error response."""
    send_response({
        "jsonrpc": "2.0",
        "id": request_id,
        "error": {"code": code, "message": message},
    })


def _get_parent_pid(pid):
    """Return the parent PID of a given process, or None on failure."""
    if sys.platform == "win32":
        try:
            ps_cmd = (
                f'(Get-CimInstance Win32_Process -Filter '
                f'"ProcessId = {pid}").ParentProcessId'
            )
            result = subprocess.run(
                ["powershell", "-NoProfile", "-Command", ps_cmd],
                capture_output=True, text=True, timeout=5,
            )
            val = result.stdout.strip()
            return int(val) if val.isdigit() else None
        except (subprocess.TimeoutExpired, FileNotFoundError, ValueError, OSError):
            return None
    # Linux: /proc/<pid>/stat field 4 is ppid
    try:
        stat_path = f"/proc/{pid}/stat"
        if os.path.exists(stat_path):
            with open(stat_path, "r") as f:
                fields = f.read().split()
            return int(fields[3]) if len(fields) > 3 else None
    except (OSError, ValueError, IndexError):
        pass
    # macOS: ps -p PID -o ppid=
    try:
        result = subprocess.run(
            ["ps", "-ww", "-p", str(pid), "-o", "ppid="],
            capture_output=True, text=True, timeout=5,
        )
        val = result.stdout.strip()
        return int(val) if val else None
    except (subprocess.TimeoutExpired, FileNotFoundError, ValueError, OSError):
        return None


def _is_orphan(pid):
    """Return True if the given bridge process is an orphan (parent dead)."""
    ppid = _get_parent_pid(pid)
    if ppid is None:
        return True  # Can't determine -- assume orphan (safe to kill)
    if ppid <= 1:
        return True  # Reparented to init/launchd
    return not is_process_alive(ppid)


def _cmdline_targets_port(cmdline, port):
    """True when a bridge command line targets EXACTLY this port.

    The old test was `"--port" in cmdline and str(port) in cmdline`, a
    substring match: cleaning up port 9870 also matched a bridge running
    on 19870 or 98700, so a peer session's bridge could be terminated.
    Match the flag and its value as ADJACENT TOKENS, mirroring the
    bridge's own parse_args exactly -- which supports only the space
    form. Accepting `--port=9870` would be actively wrong: a bridge
    invoked that way parses no port at all and is really running on the
    DEFAULT port, so treating it as a match would kill the wrong bridge.
    """
    if not cmdline:
        return False
    # /proc/<pid>/cmdline is NUL-separated; ps output is space-separated.
    tokens = [t for t in cmdline.replace(chr(0), " ").split() if t]
    target = str(port)
    for i, tok in enumerate(tokens):
        if tok == "--port":
            if i + 1 < len(tokens) and tokens[i + 1] == target:
                return True
    return False


def kill_stale_bridges(port, config_path):
    """Find and terminate stale envoy-bridge processes.

    Phase 1: Kill bridges with stale heartbeat files (>HEARTBEAT_STALE_S old).
    This is the primary detection mechanism -- fast, reliable, no parent PID
    assumptions.

    Phase 2 (legacy fallback): For bridges that predate heartbeat files, fall
    back to pgrep/tasklist + _is_orphan() parent-PID checking.
    """
    my_pid = os.getpid()

    # --- Phase 1: Heartbeat-based detection ---
    stale = _list_stale_heartbeats(config_path, HEARTBEAT_STALE_S)
    for pid, age in stale:
        if pid == my_pid:
            continue
        try:
            if sys.platform == "win32":
                subprocess.run(
                    ["taskkill", "/F", "/PID", str(pid)],
                    capture_output=True, timeout=5,
                )
            else:
                os.kill(pid, signal.SIGTERM)
            log(f"Terminated stale bridge (PID {pid}, heartbeat {age:.0f}s old)")
        except (ProcessLookupError, PermissionError, OSError,
                subprocess.TimeoutExpired):
            pass

    # --- Phase 2: Legacy fallback (pgrep/tasklist + orphan check) ---
    if sys.platform == "win32":
        try:
            ps_cmd = (
                f'Get-CimInstance Win32_Process -Filter '
                f'"Name like \'%python%\'" | '
                f'Where-Object {{ $_.CommandLine -match "envoy.bridge" -and '
                # Anchor the port so cleaning 9870 cannot match a peer
                # bridge on 19870/98700 -- the POSIX branch got this fix
                # via _cmdline_targets_port; the two must agree.
                f'$_.CommandLine -match "--port {port}(\\s|$)" -and '
                f'$_.ProcessId -ne {my_pid} }} | '
                f'Select-Object ProcessId, ParentProcessId | '
                f'ForEach-Object {{ "$($_.ProcessId),$($_.ParentProcessId)" }}'
            )
            result = subprocess.run(
                ["powershell", "-NoProfile", "-Command", ps_cmd],
                capture_output=True, text=True, timeout=10,
            )
            for line in result.stdout.strip().split("\n"):
                line = line.strip()
                if not line:
                    continue
                parts = line.split(",")
                if len(parts) < 2 or not parts[0].isdigit():
                    continue
                pid = int(parts[0])
                ppid = int(parts[1]) if parts[1].isdigit() else 0
                # Only kill if parent is dead (orphan)
                if ppid > 1 and is_process_alive(ppid):
                    continue
                try:
                    subprocess.run(
                        ["taskkill", "/F", "/PID", str(pid)],
                        capture_output=True, timeout=5,
                    )
                    log(f"Terminated orphan bridge (PID {pid}, parent {ppid} dead)")
                except (subprocess.TimeoutExpired, OSError):
                    pass
        except (subprocess.TimeoutExpired, FileNotFoundError, OSError):
            pass
        return
    try:
        result = subprocess.run(
            ["pgrep", "-f", "envoy-bridge.py"],
            capture_output=True, text=True, timeout=5,
        )
        if result.returncode != 0:
            return
        for line in result.stdout.strip().split("\n"):
            line = line.strip()
            if not line:
                continue
            try:
                pid = int(line)
            except ValueError:
                continue
            if pid == my_pid:
                continue
            try:
                cmdline_path = f"/proc/{pid}/cmdline"
                if os.path.exists(cmdline_path):
                    with open(cmdline_path, "r") as f:
                        cmdline = f.read()
                else:
                    ps = subprocess.run(
                        ["ps", "-ww", "-p", str(pid), "-o", "args="],
                        capture_output=True, text=True, timeout=5,
                    )
                    cmdline = ps.stdout.strip()
                if _cmdline_targets_port(cmdline, port):
                    if _is_orphan(pid):
                        os.kill(pid, signal.SIGTERM)
                        log(f"Terminated orphan bridge (PID {pid})")
                    else:
                        log(f"Skipping active peer bridge (PID {pid}, parent alive)")
            except (ProcessLookupError, PermissionError, OSError):
                pass
    except (subprocess.TimeoutExpired, FileNotFoundError, ValueError):
        pass


def start_orphan_watchdog(stdin_probe_fd, config_path):
    """Start a daemon thread that exits when the MCP client's stdin pipe closes.

    Detects session end via POLLHUP on a dup'd stdin fd (macOS/Linux) or
    PeekNamedPipe failure (Windows).  This replaces the old ppid-based
    detection which failed because the VS Code extension host (the actual
    parent) outlives individual Claude Code sessions.
    """
    def watchdog():
        try:
            if sys.platform == "win32":
                import ctypes
                import msvcrt
                handle = msvcrt.get_osfhandle(stdin_probe_fd)
                kernel32 = ctypes.windll.kernel32
                while True:
                    time.sleep(STDIN_POLL_INTERVAL_MS / 1000)
                    avail = ctypes.c_ulong(0)
                    ok = kernel32.PeekNamedPipe(
                        handle, None, 0, None, ctypes.byref(avail), None)
                    if not ok:
                        log("stdin pipe broken (Windows). Session ended. Exiting.")
                        _cleanup_heartbeat(config_path)
                        os._exit(0)
            else:
                import select as _select
                poller = _select.poll()
                poller.register(stdin_probe_fd,
                                _select.POLLIN | _select.POLLHUP)
                while True:
                    events = poller.poll(STDIN_POLL_INTERVAL_MS)
                    for fd, event in events:
                        if event & (_select.POLLHUP | _select.POLLERR
                                    | _select.POLLNVAL):
                            log("stdin pipe closed (POLLHUP). "
                                "Session ended. Exiting.")
                            _cleanup_heartbeat(config_path)
                            os._exit(0)
        except Exception as e:
            log(f"Orphan watchdog error: {type(e).__name__}: {e}")
            # Never let the watchdog die silently -- retry. This MUST be a
            # loop, not a recursive self-call: a persistently failing
            # poll() (closed or invalid dup'd fd) added a stack frame per
            # retry until RecursionError killed the thread silently.
            time.sleep(STDIN_POLL_INTERVAL_MS / 1000)
            return False        # caller re-enters
        return True

    def watchdog_forever(max_failures=WATCHDOG_MAX_FAILURES):
        """Re-enter on failure instead of recursing (see watchdog()).

        BOUNDED: the old code recursed and died of RecursionError; an
        unbounded loop is not the fix either, because this thread's whole
        job is to call os._exit(0) -- a permanently broken poll spinning
        forever is a hot loop attached to a process-killer. After
        max_failures consecutive failures, log loudly and stop watching.
        The session then relies on ordinary stdin EOF handling in the
        main loop, which is the same posture as a bridge built without a
        watchdog at all.
        """
        failures = 0
        while failures < max_failures:
            if watchdog():
                return          # clean exit path (never reached today)
            failures += 1
        log(f"Orphan watchdog gave up after {max_failures} consecutive "
            f"failures -- session-end detection is now handled by the "
            f"main stdin loop only.")

    t = threading.Thread(target=watchdog_forever, daemon=True,
                         name="orphan-watchdog")
    t.start()


def wait_for_envoy(url, deadline):
    """Block until Envoy is reachable or deadline expires. Returns True on success."""
    attempt = 0
    while time.monotonic() < deadline:
        try:
            # Probe with an empty POST -- any HTTP response (even 4xx/5xx)
            # means the server is up.  Only connection errors (refused,
            # timeout, DNS) indicate it's not running yet.
            urllib.request.urlopen(
                urllib.request.Request(
                    url, data=b"{}",
                    headers={
                        "Content-Type": "application/json",
                        "Accept": "application/json, text/event-stream",
                    },
                ),
                timeout=3,
            )
            return True
        except urllib.error.HTTPError:
            # Server responded (maybe 400/405) -- it's reachable
            return True
        except (urllib.error.URLError, ConnectionError, OSError):
            # Connection refused / timeout -- server not up yet
            pass
        idx = min(attempt, len(RETRY_INTERVALS) - 1)
        wait = RETRY_INTERVALS[idx]
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            break
        actual_wait = min(wait, remaining)
        elapsed = CONNECT_TIMEOUT_S - remaining
        log(f"Waiting for Envoy ({elapsed:.0f}s elapsed, retry in {actual_wait:.1f}s). "
            f"Ensure TouchDesigner is running with Envoy enabled.")
        time.sleep(actual_wait)
        attempt += 1
    return False


