def handle_get_td_status(state):
    """Handle the get_td_status meta-tool."""
    with state:
        td_pid = state.td_pid
        last_connected_time = state.last_connected_time
        launch_timestamps = list(state.launch_timestamps)
        connected = state.connected
        config_path = state.config_path

    # Refresh process liveness. The PORT answering is the strongest
    # identity signal (the instance registered it itself); a verified
    # registered pid is second. NEVER infer liveness from unrelated TD
    # processes -- on multi-instance machines that reported dead
    # instances as alive (issue #57 follow-up).
    alive = bool(connected) or is_td_process_alive(td_pid)
    if td_pid and not alive:
        with state:
            state.crash_detected = True

    last_ts = None
    if last_connected_time is not None:
        last_ts = time.strftime(
            "%Y-%m-%dT%H:%M:%SZ", time.gmtime(last_connected_time))

    remaining = CRASH_LOOP_MAX - len([
        t for t in launch_timestamps
        if t > time.monotonic() - CRASH_LOOP_WINDOW_S
    ])

    # Include instance registry with reachability
    config = load_config(config_path)
    instance_status, active_name, unregistered = get_instance_status(config)

    with state:
        crash_detected = state.crash_detected

    status = {
        "connected": connected,
        "td_process_alive": alive,
        "crash_detected": crash_detected,
        "last_connected": last_ts,
        "td_executable": config.get("td_executable", ""),
        "restart_attempts_remaining": max(0, remaining),
        "active_instance": active_name,
        "pinned_instance": _HEARTBEAT_PIN.get("name"),
        "instances": instance_status,
    }
    sessions = _list_live_sessions(config_path)
    if sessions:
        status["sessions"] = sessions
    if unregistered:
        status["unregistered_td_processes"] = unregistered
    convoy_pin = _convoy_pin_snapshot(state)
    if convoy_pin is not None:
        # This report is about the LOCAL instance, but ordinary tools are
        # relayed to the pinned remote node until convoy_select_node(clear=true)
        # (or switch_instance) clears it.
        status["convoy_pin"] = convoy_pin
    return status


def handle_switch_instance(params, state):
    """Handle the switch_instance meta-tool (session-local by default)."""
    with state:
        config_path = state.config_path
        my_pin = state.pinned_instance
    config = load_config(config_path)
    instance_status, active_name, _unreg = get_instance_status(config)

    target = params.get("instance")
    all_sessions = bool(params.get("all_sessions"))

    # List mode: no target specified
    if not target:
        return {
            "status": "list",
            "active_instance": active_name,
            "pinned_instance": my_pin,
            "instances": instance_status,
        }

    # Switch mode: target specified
    if target not in config.get("instances", {}):
        return {
            "status": "error",
            "message": f'Instance "{target}" not found in registry.',
            "available": list(instance_status.keys()),
        }

    info = config["instances"][target]
    target_port = info.get("port")

    # Verify the target instance is reachable
    if not ping_envoy_port(target_port):
        return {
            "status": "error",
            "message": (
                f'Instance "{target}" (port {target_port}) is not reachable. '
                "Is TouchDesigner running with Envoy enabled?"
            ),
        }

    # Switch the bridge's in-memory state
    old_active = active_name
    config_pid = info.get("td_pid")
    # Registry pid only (image-verified) -- never a blind any-TD fallback,
    # which could name a DIFFERENT instance's process (issue #57 follow-up).
    resolved_pid = (config_pid
                    if config_pid and is_td_process_alive(config_pid)
                    else None)
    with state:
        old_url = state.url
        state.url = f"http://127.0.0.1:{target_port}/mcp"
        state.connected = False  # Force reconnect + initialize handshake
        state.td_pid = resolved_pid
        state.crash_detected = False
        state.config = config
        state.active_name = target
        # Session-local re-pin: THIS bridge follows the target from now
        # on; peers' routing is untouched (their pins hold).
        state.pinned_instance = target
        _HEARTBEAT_PIN["name"] = target
        # Switching to a LOCAL instance while a Convoy pin is set is a
        # contradiction: without this, switch_instance returned success but the
        # ordinary-tool relay branch still routed every call to the pinned
        # REMOTE node, so a follow-up delete_op / import_network executed on the
        # remote machine.  Clearing the pin makes "come back local" mean it.
        previous_convoy_target = (
            dict(state.convoy_target)
            if isinstance(state.convoy_target, dict) else None)
        state.convoy_target = None
        # Invalidate cache -- new backend must be re-verified
        state.cached_tools = None
        state.cached_tools_hash = None
    if previous_convoy_target is not None:
        # Best-effort: tell the pinned host this controller released the node.
        try:
            _publish_convoy_controller(
                previous_convoy_target, clear_selected=True)
        except Exception as exc:
            log("switch_instance convoy release heartbeat failed: %s"
                % type(exc).__name__)
    if all_sessions and config_path:
        # Explicit whole-user switch: write the registry default AND bump
        # active_epoch -- pinned bridges treat an epoch increase as a
        # command that overrides their pin (ordinary 'active' churn does
        # not). Re-read from disk to minimize race window with other
        # bridges writing simultaneously.
        try:
            fresh = load_config(config_path) or {}
            fresh["active"] = target
            try:
                fresh["active_epoch"] = int(fresh.get("active_epoch") or 0) + 1
            except (TypeError, ValueError):
                fresh["active_epoch"] = 1
            atomic_write_json(config_path, fresh)
            with state:
                state.seen_epoch = fresh["active_epoch"]
        except Exception as e:
            log(f"Warning: could not update envoy.json: {e}")

    scope = "ALL sessions" if all_sessions else "this session only"
    log(f"Switched from '{old_active}' to '{target}' "
        f"(port {target_port}, {scope})")

    # Give the client immediate feedback that the tool list may have
    # changed -- the reconciler will re-verify on the next tick and clean
    # up the cache, but we don't wait for it here.
    # NOTE: Claude Code ignores this notification (bug anthropics/claude-code#13646).
    # Kept for future-proofing -- will start working when the bug is fixed.
    try:
        notify_stdout("notifications/tools/list_changed")
    except Exception as e:
        log(f"notify_stdout failed in switch_instance: "
            f"{type(e).__name__}: {e}")

    message = (f'Switched to instance "{target}" on port {target_port} '
               + ("for ALL sessions." if all_sessions
                  else "for this session only (peers unaffected)."))
    if previous_convoy_target is not None:
        message += (" Cleared the active Convoy pin -- ordinary tools now run "
                    "on this local instance again.")
    result = {
        "status": "success",
        "message": message,
        "instance": target,
        "port": target_port,
        "all_sessions": all_sessions,
        "toe_path": info.get("toe_path", ""),
    }
    if previous_convoy_target is not None:
        result["cleared_convoy_pin"] = previous_convoy_target
    return result


def handle_launch_td(params, state):
    """Handle the launch_td meta-tool."""
    timeout = params.get("timeout", 120)
    project_path = params.get("project_path")

    with state:
        config = state.config
        config_path = state.config_path

    # Resolve the target .toe so we can check whether THIS specific
    # instance is already running. Other TDs (different .toe, unrelated
    # projects) are fine -- launching alongside them is supported.
    if project_path:
        if not os.path.isabs(project_path) and config_path:
            embody_dir = os.path.dirname(os.path.abspath(config_path))
            git_root = os.path.dirname(embody_dir)
            target_toe = os.path.join(git_root, project_path)
        else:
            target_toe = project_path
    else:
        target_toe = resolve_toe_path(config, config_path)

    if target_toe:
        target_abs = os.path.abspath(target_toe)
        target_basename = os.path.basename(target_toe)
        if target_basename.endswith(".toe"):
            target_basename = target_basename[:-4]
        instances = config.get("instances", {})

        # Fast path: direct key lookup. Refuses if an instance is
        # registered under the target's basename with a live PID.
        instance_info = instances.get(target_basename, {})
        existing_pid = instance_info.get("td_pid")
        # Image-verified liveness: a recycled pid that now belongs to some
        # unrelated process must not block a legitimate relaunch.
        if existing_pid and is_td_process_alive(existing_pid):
            return {
                "status": "error",
                "message": (
                    f'Instance "{target_basename}" is already running '
                    f"(PID {existing_pid}). Use switch_instance to use "
                    "it, or close it first to relaunch."
                ),
            }

        # PID-aware path: scan every instance whose td_pid is alive
        # and whose registered toe_path (after walk-forward) resolves
        # to the same target file. Catches the stale-key edge case --
        # registry still keyed under an older basename, but the live
        # process IS the one we're about to launch a duplicate of.
        if config_path:
            embody_dir = os.path.dirname(os.path.abspath(config_path))
            git_root = os.path.dirname(embody_dir)
        else:
            git_root = None
        for key, info in instances.items():
            pid = info.get("td_pid", 0)
            if not pid or not is_td_process_alive(pid):
                continue
            their_toe = info.get("toe_path", "")
            if not their_toe:
                continue
            if not os.path.isabs(their_toe) and git_root:
                their_toe = os.path.join(git_root, their_toe)
            their_resolved = find_latest_versioned_toe(their_toe)
            if os.path.abspath(their_resolved) == target_abs:
                return {
                    "status": "error",
                    "message": (
                        f'Instance "{key}" (PID {pid}) is already running '
                        f"the target .toe (resolved to "
                        f"{os.path.basename(target_abs)}). The registry "
                        f"key may be stale -- use switch_instance to use "
                        f"it, or close it first to relaunch."
                    ),
                }

    # Crash-loop guard
    now = time.monotonic()
    with state:
        recent = [t for t in state.launch_timestamps
                  if t > now - CRASH_LOOP_WINDOW_S]
    if len(recent) >= CRASH_LOOP_MAX:
        return {
            "status": "error",
            "message": (
                f"TouchDesigner has crashed {CRASH_LOOP_MAX} times in the "
                f"last {CRASH_LOOP_WINDOW_S // 60} minutes. Something may be "
                "wrong with the project. Ask the user to investigate."
            ),
        }

    # Snapshot existing TD PIDs so launch_td can identify the spawned
    # process by exclusion on macOS.
    pre_launch_pids = find_all_td_pids()

    # Launch
    success, message, pid = launch_td(config, config_path,
                                      project_path=project_path,
                                      existing_pids=pre_launch_pids)
    if not success:
        return {"status": "error", "message": message}

    with state:
        state.td_pid = pid
        state.crash_detected = False
        state.launch_timestamps.append(time.monotonic())
        url = state.url
    log(message)

    # Wait for Envoy to become reachable
    deadline = time.monotonic() + timeout
    if wait_for_envoy(url, deadline):
        with state:
            state.connected = True
            state.last_connected_time = time.time()
        log("Envoy is reachable after TD launch")
        return {
            "status": "success",
            "message": ("TouchDesigner launched and Envoy is ready. "
                        + _pid_phrase(pid)),
        }
    else:
        return {
            "status": "partial",
            "message": (
                f"TouchDesigner launched ({_pid_phrase(pid)}) but Envoy not "
                f"reachable after {timeout}s. TD may still be loading -- "
                "Embody needs ~75 frames to complete restoration."
            ),
        }


def _pid_phrase(pid):
    """Human phrase for a pid that may be unresolved.

    macOS `open -n -a` hands off to LaunchServices and returns no pid, so
    the poll can time out with TD genuinely still coming up. Printing
    "PID None" reads as a bug and hides the real state; say it plainly
    instead. Used by every user-facing launch/restart message.
    """
    return f"PID {pid}" if pid else "pid not yet resolved"


def handle_restart_td(params, state):
    """Handle the restart_td meta-tool."""
    timeout = params.get("timeout", 120)
    project_path = params.get("project_path")

    # Quit ONLY the ACTIVE instance's verified process. The old find_td_pid()
    # here grabbed the first TD on the machine -- with several instances
    # running, restart_td could quit a DIFFERENT project's TD entirely
    # (issue #57 follow-up). Identity comes from the registry (written by
    # the instance itself), falling back to the bridge's own launch-tracked
    # pid; both are image-verified against pid reuse.
    with state:
        cfg_path = state.config_path
        state_pid = state.td_pid
    cfg = load_config(cfg_path)
    _port, reg_pid, active_name = _resolve_from_registry(cfg, None)
    pid = reg_pid if reg_pid and is_td_process_alive(reg_pid) else None
    if pid is None and state_pid and is_td_process_alive(state_pid):
        pid = state_pid
    if not pid:
        return {
            "status": "error",
            "message": (
                f'The active instance'
                f'{f" ({active_name})" if active_name else ""} is not '
                "running (no verified TouchDesigner process for it -- other "
                "TD instances are ignored). Use launch_td to start it."
            ),
        }

    log(f"Restarting TouchDesigner (PID {pid})")
    success, quit_msg = quit_td(pid)
    log(quit_msg)
    if not success:
        return {"status": "error", "message": quit_msg}

    # Clear connection state
    with state:
        state.connected = False
        state.td_pid = None
        state.crash_detected = False
        config = state.config
        config_path = state.config_path

    # Launch fresh (optionally with a different .toe). Snapshot the SURVIVING
    # TD pids after the quit so darwin's pid-diff attribution excludes every
    # foreign instance -- with no snapshot the polling helper adopts the
    # oldest foreign TD as ours on multi-instance machines, and a later
    # restart would aim its quit at the user's other session.
    surviving_pids = find_all_td_pids()
    success, launch_msg, new_pid = launch_td(config, config_path,
                                              project_path=project_path,
                                              existing_pids=surviving_pids)
    if not success:
        return {"status": "error", "message": launch_msg}

    with state:
        state.td_pid = new_pid
        state.launch_timestamps.append(time.monotonic())
        url = state.url
    log(launch_msg)

    # Wait for Envoy to become reachable
    deadline = time.monotonic() + timeout
    if wait_for_envoy(url, deadline):
        with state:
            state.connected = True
            state.last_connected_time = time.time()
        log("Envoy is reachable after TD restart")
        return {
            "status": "success",
            "message": (
                f"TouchDesigner restarted and Envoy is ready. "
                f"Old PID: {pid}, new {_pid_phrase(new_pid)}"
            ),
        }
    else:
        return {
            "status": "partial",
            "message": (
                f"TouchDesigner relaunched ({_pid_phrase(new_pid)}) but Envoy not "
                f"reachable after {timeout}s. TD may still be loading -- "
                "Embody needs ~75 frames to complete restoration."
            ),
        }


def handle_bridge_tool(name, params, state):
    """Dispatch a bridge meta-tool call. Returns the tool result content."""
    if name == "get_td_status":
        result = handle_get_td_status(state)
    elif name == "launch_td":
        result = handle_launch_td(params, state)
    elif name == "restart_td":
        result = handle_restart_td(params, state)
    elif name == "switch_instance":
        result = handle_switch_instance(params, state)
    elif name == "get_convoy_status":
        result = handle_convoy_status(params)
    elif name == "convoy_list_nodes":
        result = handle_convoy_list_nodes(params)
    elif name == "convoy_select_node":
        result = handle_convoy_select_node(params, state)
    elif name == "convoy_owlette":
        result = handle_convoy_owlette(params)
    elif name == "convoy_list_controllers":
        result = handle_convoy_list_controllers(params)
    elif name == "convoy_ping":
        result = handle_convoy_ping(params)
    elif name == "convoy_start_node":
        result = handle_convoy_start_node(params)
    elif name == "convoy_restart_node":
        result = handle_convoy_restart_node(params)
    elif name == "convoy_update_embody":
        result = handle_convoy_update_embody(params)
    elif name == "convoy_call":
        result = handle_convoy_call(params)
    elif name == "convoy_batch":
        result = handle_convoy_batch(params)
    elif name == "convoy_get_job":
        result = handle_convoy_get_job(params)
    elif name == "convoy_ack_job":
        result = handle_convoy_ack_job(params)
    elif name == "convoy_get_artifact":
        result = handle_convoy_get_artifact(params)
    elif name == "convoy_save_artifact":
        result = handle_convoy_save_artifact(params, state)
    elif name == "convoy_cancel_job":
        result = handle_convoy_cancel_job(params)
    elif name == "convoy_forget_node":
        result = handle_convoy_forget_node(params)
    else:
        result = {"error": f"Unknown bridge tool: {name}"}

    # These local process-management tools act on the LOCAL TD, but ordinary
    # tools are still relayed to any active Convoy pin -- surface it so the
    # split is never invisible (get_td_status already reports it internally).
    if (name in ("launch_td", "restart_td")
            and isinstance(result, dict) and "convoy_pin" not in result):
        convoy_pin = _convoy_pin_snapshot(state)
        if convoy_pin is not None:
            result["convoy_pin"] = convoy_pin

    if name == "convoy_get_artifact":
        return convoy_artifact_mcp_content(result)
    if name in ("convoy_call", "convoy_get_job"):
        materialized = materialize_convoy_relay_image(result, params)
        if materialized is not None:
            rendered = convoy_artifact_mcp_content(materialized)
            summary = {"relay": result,
                       "artifact_materialization": materialized}
            return ([{"type": "text",
                      "text": json.dumps(summary, indent=2)}]
                    + [block for block in rendered
                       if block.get("type") == "image"])
    return [{"type": "text", "text": json.dumps(result, indent=2)}]


