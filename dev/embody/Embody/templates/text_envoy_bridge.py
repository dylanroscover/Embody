def _convoy_lifecycle_call(params, operation):
    required = ["target_host_id", "convoy_id", "target_node_id"]
    if operation == "convoy_restart_node":
        required.append("expected_runtime_id")
    invalid = _convoy_required_text(params, tuple(required))
    if invalid:
        return _convoy_invalid_arguments(invalid)
    timeout_s = params.get("timeout_s", 120.0)
    if (isinstance(timeout_s, bool)
            or not isinstance(timeout_s, (int, float))
            or not math.isfinite(float(timeout_s))
            or not 0.1 <= float(timeout_s) <= 900.0):
        return _convoy_invalid_arguments(
            "timeout_s must be finite and within [0.1, 900]")
    wait = params.get("wait", True)
    if not isinstance(wait, bool):
        return _convoy_invalid_arguments("wait must be true or false")
    arguments = {"timeout_s": float(timeout_s)}
    if operation == "convoy_restart_node":
        policy = params.get("policy", "require_clean")
        if policy not in ("require_clean", "save_then_restart"):
            return _convoy_invalid_arguments("restart policy is not supported")
        arguments["policy"] = policy
    call = {name: params[name] for name in required}
    call.update({
        "operation": operation,
        "arguments": arguments,
        "timeout_s": float(timeout_s),
        "wait": wait,
    })
    if "idempotency_key" in params:
        call["idempotency_key"] = params["idempotency_key"]
    result = handle_convoy_call(call)
    result = dict(result) if isinstance(result, dict) else {
        "ok": False, "reason": "convoy_host_bad_response"}
    result["starts_touchdesigner"] = operation == "convoy_start_node"
    result["restarts_touchdesigner"] = operation == "convoy_restart_node"
    return result


def handle_convoy_start_node(params):
    """Start one exact host-pinned offline node."""
    return _convoy_lifecycle_call(params, "convoy_start_node")


def handle_convoy_restart_node(params):
    """Restart one exact runtime with an explicit dirty-state policy."""
    return _convoy_lifecycle_call(params, "convoy_restart_node")


def _convoy_call_body(params):
    invalid = _convoy_required_text(
        params, ("target_host_id", "convoy_id", "target_node_id",
                 "operation"))
    if invalid:
        return None, _convoy_invalid_arguments(invalid)
    arguments = params.get("arguments", {})
    if not isinstance(arguments, dict):
        return None, _convoy_invalid_arguments("arguments must be an object")
    for optional_text in ("expected_runtime_id", "idempotency_key"):
        value = params.get(optional_text)
        if value is not None and (
                not isinstance(value, str) or not value.strip()):
            return None, _convoy_invalid_arguments(
                "%s must be a non-empty string when supplied" % optional_text)
    wait = params.get("wait", True)
    if not isinstance(wait, bool):
        return None, _convoy_invalid_arguments("wait must be true or false")
    timeout_s = params.get("timeout_s", 30.0)
    if (isinstance(timeout_s, bool)
            or not isinstance(timeout_s, (int, float))
            or not math.isfinite(float(timeout_s))
            or float(timeout_s) < 0.1 or float(timeout_s) > 3600.0):
        return None, _convoy_invalid_arguments(
            "timeout_s must be finite and within [0.1, 3600]")
    body = {name: params.get(name) for name in (
        "target_host_id", "convoy_id", "target_node_id", "operation",
        "expected_runtime_id") if params.get(name) is not None}
    body["arguments"] = arguments
    body["timeout_s"] = float(timeout_s)
    body["idempotency_key"] = (
        params.get("idempotency_key") or uuid.uuid4().hex)
    body["controller_id"] = _CONVOY_CONTROLLER_ID
    return body, None


def handle_convoy_update_embody(params):
    """Fan the bounded update_embody operation out over Convoy nodes.

    Fleet updates must not require the TD Python grant (field
    2026-08-19): update_embody is its own registered operation, so this
    dispatches durable jobs and hands back the delivery handles rather
    than parking on a fleet-wide wait.
    """
    if not isinstance(params, dict):
        return _convoy_invalid_arguments("arguments must be an object")
    node = params.get("node")
    do_all = params.get("all", False)
    if node is not None and (not isinstance(node, str) or not node.strip()):
        return _convoy_invalid_arguments(
            "node must be a non-empty string when supplied")
    if not isinstance(do_all, bool):
        return _convoy_invalid_arguments("all must be true or false")
    if bool(node) == bool(do_all):
        return _convoy_invalid_arguments(
            "pass exactly one of node=<id|name|hostname> or all=true")
    listing_args = {}
    if params.get("convoy_id") is not None:
        listing_args["convoy_id"] = params["convoy_id"]
    listing = handle_convoy_list_nodes(listing_args)
    if not isinstance(listing, dict) or not listing.get("ok"):
        return listing if isinstance(listing, dict) else {
            "ok": False, "reason": "convoy_host_bad_response"}
    rows = listing.get("nodes")
    if not isinstance(rows, list):
        return {"ok": False, "reason": "convoy_host_bad_response",
                "detail": "the node directory response carried no nodes"}

    def _label(row):
        return (row.get("node_name") or row.get("hostname")
                or row.get("node_id") or "?")

    if node:
        needle = node.strip()
        matched = [row for row in rows if isinstance(row, dict) and needle in
                   (row.get("node_id"), row.get("node_name"),
                    row.get("hostname"))]
        if not matched:
            return {"ok": False, "reason": "node_not_found",
                    "detail": "no node matched %r by node_id, node_name, "
                              "or hostname" % needle,
                    "known": [_label(row) for row in rows
                              if isinstance(row, dict)][:32]}
        if len(matched) > 1:
            return {"ok": False, "reason": "node_ambiguous",
                    "detail": "%d nodes matched %r -- use the node_id"
                              % (len(matched), needle),
                    "matches": [{"node_id": row.get("node_id"),
                                 "node_name": row.get("node_name")}
                                for row in matched]}
        candidates = matched
    else:
        candidates = [row for row in rows if isinstance(row, dict)]

    dispatched, skipped = [], []
    for row in candidates:
        label = _label(row)
        if not bool(row.get("enabled", True)):
            skipped.append({"node": label, "reason": "disabled"})
            continue
        if row.get("status") != "online" or not row.get("online"):
            skipped.append({"node": label, "reason": "offline"})
            continue
        if bool(row.get("perform_mode")):
            # Envoy is suspended during a show; the update cannot land.
            skipped.append({"node": label, "reason": "perform_mode"})
            continue
        required = (row.get("host_id"), row.get("convoy_id"),
                    row.get("node_id"))
        if not all(isinstance(v, str) and v for v in required):
            skipped.append({"node": label, "reason": "incomplete_row"})
            continue
        call = {
            "target_host_id": row["host_id"],
            "convoy_id": row["convoy_id"],
            "target_node_id": row["node_id"],
            "operation": "update_embody",
            "arguments": {},
            "wait": False,
            "timeout_s": params.get("timeout_s", 30),
            "idempotency_key": "update-embody-" + uuid.uuid4().hex,
        }
        outcome = handle_convoy_call(call)
        outcome = (dict(outcome) if isinstance(outcome, dict)
                   else {"ok": False, "reason": "convoy_host_bad_response"})
        entry = {
            "node": label,
            "node_id": row["node_id"],
            "host_id": row["host_id"],
            "embody_version": row.get("embody_version"),
            "ok": bool(outcome.get("ok")),
            "idempotency_key": call["idempotency_key"],
        }
        if outcome.get("delivery_id"):
            entry["delivery_id"] = outcome["delivery_id"]
        if not outcome.get("ok"):
            entry["reason"] = outcome.get("reason")
            entry["detail"] = outcome.get("detail")
        dispatched.append(entry)

    return {
        "ok": True,
        "dispatched": dispatched,
        "skipped": skipped,
        "wakes_touchdesigner": True,
        "hint": "Each dispatch is a durable per-node job: poll with "
                "convoy_get_job(delivery_id=...). A node already at the "
                "latest release finishes 'done' with versions equal; a "
                "node older than 6.0.257 refuses update_embody as an "
                "unknown operation and needs one manual update first.",
    }


def handle_convoy_call(params):
    body, error = _convoy_call_body(params)
    if error is not None:
        return error

    # The caller's timeout covers submit + optional wait.  A durable target
    # job may outlive it; timeout therefore never implies non-execution.
    started = time.monotonic()
    timeout_s = body["timeout_s"]
    # Never park the stdio thread for the full caller budget: cap the in-loop
    # wait at CONVOY_INLINE_WAIT_MAX_S and hand back the durable delivery_id so
    # the caller finishes the wait with convoy_get_job.  The submit still uses
    # the caller's timeout (already bounded by CONVOY_HOST_TIMEOUT_S below).
    wait_budget = min(timeout_s, CONVOY_INLINE_WAIT_MAX_S)
    inline_wait_capped = wait_budget < timeout_s
    deadline = started + wait_budget
    accepted = convoy_host_call(
        "POST", "/relay", body,
        timeout=min(CONVOY_HOST_TIMEOUT_S, timeout_s))
    accepted = _convoy_add_provenance(
        accepted, body, include_operation=True)

    if not accepted.get("ok"):
        # Even an unanswered loopback POST may have reached the local host,
        # which in turn may have received a durable remote ACK.  Returning
        # the exact retry key lets the controller reconcile by repeating the
        # SAME call; target-side content binding prevents a different request
        # from hiding behind it.
        accepted["reconcile_with_idempotency_key"] = body["idempotency_key"]
        return accepted

    job = accepted.get("job")
    if not isinstance(job, dict) or not isinstance(
            job.get("delivery_id"), str) or not job.get("delivery_id"):
        accepted["ok"] = False
        accepted["reason"] = "convoy_host_bad_response"
        accepted["detail"] = (
            "Convoy accepted the request without a durable delivery_id")
        accepted["reconcile_with_idempotency_key"] = body["idempotency_key"]
        return accepted

    accepted["delivery_id"] = job["delivery_id"]
    if (job.get("state") in _CONVOY_TERMINAL_STATES
            or params.get("wait", True) is False):
        return accepted

    poll = {
        "target_host_id": body["target_host_id"],
        "convoy_id": body["convoy_id"],
        "delivery_id": job["delivery_id"],
    }
    cursor = job.get("updated")
    if (isinstance(cursor, (int, float)) and not isinstance(cursor, bool)
            and math.isfinite(float(cursor))):
        poll["since"] = cursor
    interval = CONVOY_POLL_INITIAL_S
    previous_state = job.get("state")
    last_poll_error = None

    while True:
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            break
        current = convoy_host_call(
            "POST", "/relay/job", dict(poll),
            timeout=min(CONVOY_HOST_TIMEOUT_S, remaining))
        if current.get("ok"):
            # `job` is promoted to accepted["job"] below -- carrying it
            # inside `remote` too shipped every result payload TWICE
            # (~2x tokens on each remote call; field report 2026-08-19).
            accepted["remote"] = {k: v for k, v in current.items()
                                  if k != "job"}
            remote_job = current.get("job")
            if isinstance(remote_job, dict):
                accepted["job"] = remote_job
                state = remote_job.get("state")
                new_cursor = current.get("cursor", remote_job.get("updated"))
                if (isinstance(new_cursor, (int, float))
                        and not isinstance(new_cursor, bool)
                        and math.isfinite(float(new_cursor))):
                    poll["since"] = new_cursor
                if state in _CONVOY_TERMINAL_STATES:
                    return accepted
                if state != previous_state:
                    interval = CONVOY_POLL_INITIAL_S
                    previous_state = state
            elif current.get("changed") is not False:
                accepted["poll_error"] = {
                    "ok": False, "reason": "convoy_host_bad_response",
                    "detail": "job poll omitted both job and changed=false",
                }
                accepted["wait_interrupted"] = True
                return accepted
            last_poll_error = None
        else:
            last_poll_error = current
            if current.get("reason") not in _CONVOY_TRANSIENT_POLL_REASONS:
                accepted["poll_error"] = current
                accepted["wait_interrupted"] = True
                accepted["detail"] = (
                    "the durable delivery was accepted, but polling was "
                    "refused; use convoy_get_job to reconcile it")
                return accepted

        remaining = deadline - time.monotonic()
        if remaining <= 0:
            break
        time.sleep(min(interval, remaining))
        interval = min(CONVOY_POLL_MAX_S, interval * 1.5)

    if last_poll_error is not None:
        accepted["poll_error"] = last_poll_error
    accepted["wait_timed_out"] = True
    if inline_wait_capped:
        # The wait was cut short by the stdio-serviceability cap, NOT by the
        # caller's timeout: say so, so the caller keeps polling instead of
        # concluding the request stalled.
        accepted["wait_capped"] = True
        accepted["detail"] = (
            "the bridge polled inline for %ss to keep the session responsive; "
            "the remote delivery remains durable -- reconcile with "
            "convoy_get_job (or the same idempotency_key)"
            % int(CONVOY_INLINE_WAIT_MAX_S))
    else:
        accepted["detail"] = ("the remote delivery remains durable; use "
                              "convoy_get_job to continue polling")
    return accepted


def handle_convoy_batch(params):
    """Fan one ordered native Envoy batch to each explicit target."""
    if not isinstance(params, dict):
        return _convoy_invalid_arguments("arguments must be an object")
    targets = params.get("targets")
    operations = params.get("operations")
    if not isinstance(targets, list) or not 1 <= len(targets) <= 32:
        return _convoy_invalid_arguments("targets must contain 1 through 32 entries")
    if not isinstance(operations, list) or not 1 <= len(operations) <= 64:
        return _convoy_invalid_arguments(
            "operations must contain 1 through 64 entries")
    wait = params.get("wait", True)
    override = params.get("override", False)
    if not isinstance(wait, bool) or not isinstance(override, bool):
        return _convoy_invalid_arguments("wait and override must be booleans")
    batch_key = params.get("idempotency_key")
    if batch_key is None:
        batch_key = uuid.uuid4().hex
    elif (not isinstance(batch_key, str)
          or not 1 <= len(batch_key) <= 256
          or batch_key != batch_key.strip()
          or not all(char.isprintable() for char in batch_key)):
        return _convoy_invalid_arguments(
            "idempotency_key must be 1 through 256 printable characters "
            "without leading or trailing whitespace")
    timeout_s = params.get("timeout_s", 30.0)
    if (isinstance(timeout_s, bool)
            or not isinstance(timeout_s, (int, float))
            or not math.isfinite(float(timeout_s))
            or not 0.1 <= float(timeout_s) <= 3600.0):
        return _convoy_invalid_arguments(
            "timeout_s must be finite and within [0.1, 3600]")

    clean_operations = []
    for index, spec in enumerate(operations):
        if not isinstance(spec, dict):
            return _convoy_invalid_arguments(
                "operation %d must be an object" % index)
        tool = spec.get("tool")
        op_params = spec.get("params", {})
        if not isinstance(tool, str) or not tool.strip():
            return _convoy_invalid_arguments(
                "operation %d needs a non-empty tool" % index)
        if tool == "batch_operations":
            return _convoy_invalid_arguments(
                "nested batch_operations is not supported")
        if not isinstance(op_params, dict):
            return _convoy_invalid_arguments(
                "operation %d params must be an object" % index)
        clean_operations.append({"tool": tool, "params": op_params})

    calls = []
    seen = set()
    for index, target in enumerate(targets):
        invalid = _convoy_required_text(
            target, ("target_host_id", "convoy_id", "target_node_id"))
        if invalid:
            return _convoy_invalid_arguments("target %d: %s" % (index, invalid))
        key = (target["target_host_id"], target["convoy_id"],
               target["target_node_id"])
        if key in seen:
            return _convoy_invalid_arguments(
                "target %d duplicates an earlier exact node" % index)
        seen.add(key)
        expected = target.get("expected_runtime_id")
        if expected is not None and (
                not isinstance(expected, str) or not expected.strip()):
            return _convoy_invalid_arguments(
                "target %d expected_runtime_id must be non-empty text" % index)
        call_params = {
            "target_host_id": key[0], "convoy_id": key[1],
            "target_node_id": key[2], "operation": "batch_operations",
            "arguments": {"operations": clean_operations,
                          "override": override},
            "timeout_s": float(timeout_s), "wait": wait,
            "idempotency_key": _convoy_batch_target_key(batch_key, {
                "target_host_id": key[0], "convoy_id": key[1],
                "target_node_id": key[2],
            }),
        }
        if expected is not None:
            call_params["expected_runtime_id"] = expected
        calls.append(call_params)

    # One deadline governs queueing plus every target call.  Without this,
    # targets waiting behind the eight-worker cap each received a fresh full
    # timeout when their worker finally started, so a 32-target batch could
    # run for four times the caller's stated bound.  When waiting, the same
    # stdio-serviceability cap that bounds handle_convoy_call also bounds the
    # cumulative as_completed park here; each unfinished target still returns
    # its durable delivery_id for a convoy_get_job reconcile.
    wait_budget = (min(float(timeout_s), CONVOY_INLINE_WAIT_MAX_S)
                   if wait else float(timeout_s))
    deadline = time.monotonic() + wait_budget

    def invoke(index):
        try:
            remaining = deadline - time.monotonic()
            if remaining < 0.1:
                return index, {
                    "ok": False,
                    "reason": "convoy_batch_timeout",
                    "detail": "the cumulative batch deadline elapsed "
                              "before this target could start",
                    "wait_timed_out": True,
                }
            call_params = dict(calls[index])
            call_params["timeout_s"] = min(
                float(call_params["timeout_s"]), remaining)
            return index, handle_convoy_call(call_params)
        except Exception as exc:
            return index, {
                "ok": False, "reason": "convoy_batch_internal_error",
                "detail": type(exc).__name__,
            }

    ordered = [None] * len(calls)
    # Keep host/socket pressure bounded even when the public target ceiling
    # is raised later.  Each target owns its own durable job and rollback is
    # deliberately not implied.
    with concurrent.futures.ThreadPoolExecutor(
            max_workers=min(8, len(calls))) as pool:
        futures = [pool.submit(invoke, index) for index in range(len(calls))]
        for future in concurrent.futures.as_completed(futures):
            index, result = future.result()
            ordered[index] = {
                "target": {name: calls[index][name] for name in (
                    "target_host_id", "convoy_id", "target_node_id")},
                "relay": result,
            }

    accepted = sum(1 for row in ordered if row["relay"].get("ok"))
    terminal_successes = 0
    terminal_failures = 0
    for row in ordered:
        outcome = _convoy_native_batch_success(
            row["relay"], len(clean_operations))
        if outcome is True:
            terminal_successes += 1
            row["native_batch_success"] = True
        elif outcome is False:
            terminal_failures += 1
            row["native_batch_success"] = False
    return {
        "ok": accepted == len(ordered) and terminal_failures == 0,
        "idempotency_key": batch_key,
        "content_digest": _convoy_batch_digest({
            "operation": "batch_operations",
            "arguments": {"operations": clean_operations,
                          "override": override},
        }),
        "target_count": len(ordered),
        "accepted_count": accepted,
        "terminal_success_count": terminal_successes,
        "terminal_failure_count": terminal_failures,
        "complete": terminal_successes + terminal_failures == len(ordered),
        "atomic": False,
        "results": ordered,
        "wakes_touchdesigner": True,
    }


def handle_convoy_selected_tool(name, arguments, state):
    """Translate one ordinary tools/call through the session's exact pin."""
    if not isinstance(arguments, dict):
        return {
            "content": [{"type": "text", "text": json.dumps({
                "ok": False, "reason": "invalid_arguments",
                "detail": "tool arguments must be an object"})}],
            "isError": True,
        }
    with state:
        target = (dict(state.convoy_target)
                  if isinstance(state.convoy_target, dict) else None)
    if target is None:
        return None
    call_params = {
        "target_host_id": target["target_host_id"],
        "convoy_id": target["convoy_id"],
        "target_node_id": target["target_node_id"],
        "operation": name,
        "arguments": arguments,
        "timeout_s": 30.0,
        "wait": True,
    }
    if target.get("expected_runtime_id"):
        call_params["expected_runtime_id"] = target["expected_runtime_id"]
    # Bind a deterministic idempotency key so an identical retry of this pinned
    # tool reconciles to the existing durable job instead of double-executing.
    selected_key = _convoy_selected_call_key(target, name, arguments)
    if selected_key is not None:
        call_params["idempotency_key"] = selected_key
    relay = handle_convoy_call(call_params)
    job = relay.get("job") if isinstance(relay, dict) else None
    state_name = job.get("state") if isinstance(job, dict) else None
    provenance = {
        "target_host_id": target["target_host_id"],
        "convoy_id": target["convoy_id"],
        "target_node_id": target["target_node_id"],
        "expected_runtime_id": target.get("expected_runtime_id"),
        "delivery_id": (relay.get("delivery_id")
                        if isinstance(relay, dict) else None),
        "state": state_name,
    }
    provenance = {key: value for key, value in provenance.items()
                  if value is not None}
    failed = (not isinstance(relay, dict) or not relay.get("ok")
              or state_name in (_CONVOY_TERMINAL_STATES - {"succeeded"}))
    materialized = materialize_convoy_relay_image(relay, call_params)
    if materialized is not None:
        rendered = convoy_artifact_mcp_content(materialized)
        content = [{
            "type": "text",
            "text": json.dumps({"convoy_target": provenance,
                                "result": (job.get("result")
                                           if isinstance(job, dict) else None),
                                "artifact_materialization": materialized},
                               ensure_ascii=False, separators=(",", ":")),
        }] + [block for block in rendered if block.get("type") == "image"]
        return {"content": content,
                "isError": failed or materialized.get("ok") is not True,
                "_meta": {"convoy": provenance}}
    if isinstance(job, dict) and state_name == "succeeded":
        payload = job.get("result")
        if (isinstance(payload, dict)
                and isinstance(payload.get("content"), list)):
            content = [{
                "type": "text",
                "text": json.dumps({"convoy_target": provenance},
                                   separators=(",", ":")),
            }] + list(payload["content"])
        else:
            content = [{
                "type": "text",
                "text": json.dumps({"convoy_target": provenance,
                                    "result": payload},
                                   ensure_ascii=False, separators=(",", ":")),
            }]
    else:
        content = [{
            "type": "text",
            "text": json.dumps({"convoy_target": provenance,
                                "relay": relay}, ensure_ascii=False,
                               separators=(",", ":")),
        }]
    return {"content": content, "isError": failed,
            "_meta": {"convoy": provenance}}


def ping_envoy_port(port):
    """Check if an Envoy server is listening on the given port.
    Returns True if something responds, False otherwise."""
    if port is None:
        return False
    import socket
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            s.settimeout(1)
            return s.connect_ex(('127.0.0.1', int(port))) == 0
    except (OSError, ValueError):
        return False


def get_instance_status(config):
    """Read the instance registry from config and check reachability.
    Returns (instances_with_status: dict, active_name: str|None,
    unregistered_td_pids: list[int])."""
    instances = config.get("instances", {})
    active = config.get("active")
    result = {}
    registered_pids = set()
    for name, info in instances.items():
        pid = info.get("td_pid")
        if pid:
            registered_pids.add(pid)
        pid_alive = is_process_alive(pid)
        port_open = ping_envoy_port(info.get("port"))
        # An instance is only reachable if its own PID is alive AND its port
        # responds.  A dead PID with an open port means a different instance
        # owns that port -- this entry is stale.
        reachable = pid_alive and port_open
        result[name] = {
            "toe_path": info.get("toe_path", ""),
            "port": info.get("port"),
            "td_pid": pid,
            "reachable": reachable,
            "active": name == active,
        }
    # Discover TD processes not in the registry
    all_td_pids = find_all_td_pids()
    unregistered = [p for p in all_td_pids if p not in registered_pids]
    return result, active, unregistered


def atomic_write_json(path, data):
    """Write JSON atomically via temp file + os.replace().
    Retries on PermissionError (Windows file-in-use).
    Uses PID-tagged temp file so concurrent bridges don't collide."""
    tmp = path + f".{os.getpid()}.tmp"
    content = json.dumps(data, indent=2) + "\n"
    for attempt in range(3):
        try:
            with open(tmp, "w", encoding="utf-8") as f:
                f.write(content)
            os.replace(tmp, path)
            return
        except PermissionError:
            if attempt < 2:
                time.sleep(0.1)
            else:
                raise


def _heartbeat_path(config_path, pid=None):
    """Return the path for this bridge's heartbeat file.

    Places it in dev/logs/ relative to the git root.  Falls back to a
    temp dir if the log directory doesn't exist.
    """
    if pid is None:
        pid = os.getpid()
    filename = f"envoy-bridge-{pid}.heartbeat"
    if config_path:
        # Config is in .embody/ - git root is one level up
        embody_dir = os.path.dirname(os.path.abspath(config_path))
        git_root = os.path.dirname(embody_dir)
        log_dir = os.path.join(git_root, "dev", "logs")
        if os.path.isdir(log_dir):
            return os.path.join(log_dir, filename)
    import tempfile
    return os.path.join(tempfile.gettempdir(), filename)


# Written by the reconciler / switch handler so the heartbeat can carry the
# bridge's current pin without taking the state lock here (best-effort field).
_HEARTBEAT_PIN = {"name": None}


def _touch_heartbeat(config_path):
    """Write PID + timestamp to our heartbeat file.  Best-effort, never raises."""
    try:
        path = _heartbeat_path(config_path)
        atomic_write_json(path, {"pid": os.getpid(), "time": time.time(),
                                 "sid": SESSION_ID,
                                 "label": SESSION_LABEL or f"pid{_MY_PID}",
                                 "pin": _HEARTBEAT_PIN.get("name")})
    except Exception:
        pass


def _cleanup_heartbeat(config_path):
    """Remove our heartbeat file.  Best-effort, never raises."""
    try:
        path = _heartbeat_path(config_path)
        if os.path.exists(path):
            os.remove(path)
    except Exception:
        pass


def _list_live_sessions(config_path):
    """Glob heartbeat files and return live bridge sessions, freshest first.

    [{pid, sid, label, age_s, self}] for bridges whose heartbeat is fresh
    and whose process is alive. Works even while TD is down (heartbeats
    are bridge-side), so get_td_status can always show who is connected.
    Best-effort: never raises.
    """
    import glob as _glob
    sessions = []
    try:
        if config_path:
            # Config is in .embody/ - git root is one level up
            embody_dir = os.path.dirname(os.path.abspath(config_path))
            git_root = os.path.dirname(embody_dir)
            log_dir = os.path.join(git_root, "dev", "logs")
        else:
            import tempfile
            log_dir = tempfile.gettempdir()
        if not os.path.isdir(log_dir):
            return sessions
        now = time.time()
        for path in _glob.glob(os.path.join(log_dir, "envoy-bridge-*.heartbeat")):
            try:
                with open(path, "r", encoding="utf-8") as f:
                    data = json.load(f)
                pid = data.get("pid")
                age = now - data.get("time", 0)
                if pid is None or age > HEARTBEAT_STALE_S * 2:
                    continue
                if pid != os.getpid() and not is_process_alive(pid):
                    continue
                sessions.append({
                    "pid": pid,
                    "sid": data.get("sid"),
                    "label": data.get("label"),
                    "age_s": round(age, 1),
                    "self": pid == os.getpid(),
                })
            except Exception:
                continue
        sessions.sort(key=lambda s: s["age_s"])
    except Exception:
        pass
    return sessions

def _list_stale_heartbeats(config_path, max_age_s):
    """Glob for heartbeat files and return [(pid, age)] for stale ones.

    Also removes heartbeat files for PIDs that are no longer alive.
    """
    import glob as _glob
    stale = []
    if config_path:
        # Config is in .embody/ - git root is one level up
        embody_dir = os.path.dirname(os.path.abspath(config_path))
        git_root = os.path.dirname(embody_dir)
        log_dir = os.path.join(git_root, "dev", "logs")
    else:
        import tempfile
        log_dir = tempfile.gettempdir()
    if not os.path.isdir(log_dir):
        return stale
    pattern = os.path.join(log_dir, "envoy-bridge-*.heartbeat")
    now = time.time()
    my_pid = os.getpid()
    for path in _glob.glob(pattern):
        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
            pid = data.get("pid")
            ts = data.get("time", 0)
            if pid is None:
                continue
            if pid == my_pid:
                continue
            # If the process is dead, clean up its heartbeat file
            if not is_process_alive(pid):
                try:
                    os.remove(path)
                except OSError:
                    pass
                continue
            age = now - ts
            if age > max_age_s:
                stale.append((pid, age))
        except (json.JSONDecodeError, OSError, KeyError, TypeError):
            continue
    return stale


def quit_td(pid, graceful_timeout=15, clock=None, sleep=None,
            platform=None):
    """Quit a running TouchDesigner process -- always pid-scoped.

    Requests termination (WM_CLOSE via taskkill on Windows -- genuinely
    graceful; SIGTERM on macOS/Linux -- abrupt but correctly targeted),
    then force-kills if needed. Returns (success: bool, message: str).

    clock/sleep/platform are injectable for tests (same pattern as
    wait_for_new_td_pid): patching the GLOBAL time module fed every
    thread in the process (uvicorn exhausted finite side_effect lists
    into StopIteration), and mocking the module's `sys` proved
    full-run-fragile -- a mocked platform silently failed to take and a
    REAL taskkill escaped to the host. Injection needs no patching at
    all.
    """
    clock = clock or time.monotonic
    sleep = sleep or time.sleep
    platform = platform or sys.platform
    if pid is None:
        return False, "No TouchDesigner PID to quit"
    if not is_process_alive(pid):
        return True, "TouchDesigner already exited"

    # ALWAYS scoped to the one target pid. The old darwin path delegated to
    # an AppleScript application-level quit, which is pid-blind: it targets
    # whichever running TouchDesigner instance the system resolves -- never
    # reliably the intended one -- so on multi-instance machines a probe
    # quit could take the user's dev session down instead. The trade-off,
    # stated plainly: macOS's only Cocoa-graceful quit path is that
    # application-level event, which cannot address a pid, so this branch
    # accepts an ABRUPT-but-correctly-targeted SIGTERM (no save dialog --
    # which no one could answer headlessly anyway; the force-kill fallback
    # below is unchanged). Source tripwire tests keep application-wide
    # quits out of this file. NOTE: darwin path unverified on a physical
    # Mac at landing time (none attached).
    try:
        if platform == "win32":
            subprocess.run(
                ["taskkill", "/PID", str(pid)],
                capture_output=True, timeout=10,
            )
        else:
            os.kill(pid, signal.SIGTERM)
    except (subprocess.TimeoutExpired, OSError) as e:
        log(f"Graceful quit failed: {e}")

    # Wait for exit
    deadline = clock() + graceful_timeout
    while clock() < deadline:
        if not is_process_alive(pid):
            return True, f"TouchDesigner (PID {pid}) exited gracefully"
        sleep(0.5)

    # Force kill
    log(f"TouchDesigner (PID {pid}) did not exit gracefully, force killing")
    try:
        if platform == "win32":
            subprocess.run(
                ["taskkill", "/F", "/PID", str(pid)],
                capture_output=True, timeout=10,
            )
        else:
            os.kill(pid, _SIGKILL)
    except (subprocess.TimeoutExpired, OSError) as e:
        return False, f"Failed to kill TouchDesigner (PID {pid}): {e}"

    # Brief wait after force kill
    sleep(1)
    if is_process_alive(pid):
        return False, f"TouchDesigner (PID {pid}) could not be terminated"

    return True, f"TouchDesigner (PID {pid}) was force-killed"


def wait_for_new_td_pid(existing_pids, timeout=15.0, poll=0.5,
                        find_pids=None, clock=None, sleep=None):
    """Resolve the pid of a TouchDesigner instance LaunchServices just spawned.

    macOS 'open -n -a' exits immediately and never reports the spawned
    process, so the launcher diffs live TD pids against the pre-launch
    snapshot. The old implementation slept a fixed 2s and diffed ONCE: a
    spawn slower than 2s silently returned None, and a concurrent foreign
    launch in that window could be misattributed with no trace. Poll the
    diff until a new pid appears or the deadline passes. Several new pids
    in the SAME poll window are logged and resolved to the lowest for
    determinism; a foreign launch landing in an EARLIER window is still
    misattributed silently -- snapshot-diff attribution cannot distinguish
    spawners, so this NARROWS the misattribution window, it does not close
    it.

    find_pids/clock/sleep are injectable so the logic is fully unit-testable
    off-platform (pure Python, no TD access).
    """
    find_pids = find_pids or find_all_td_pids
    clock = clock or time.monotonic
    sleep = sleep or time.sleep
    existing = set(existing_pids or ())
    deadline = clock() + timeout
    while True:
        new_pids = sorted(p for p in find_pids() if p not in existing)
        if new_pids:
            if len(new_pids) > 1:
                log(f"Multiple new TD pids after launch: {new_pids} -- "
                    f"attributing the lowest (concurrent launch elsewhere?)")
            return new_pids[0]
        if clock() >= deadline:
            return None
        sleep(poll)


def launch_td(config, config_path, project_path=None, existing_pids=None,
              platform=None, popen=None):
    """Launch TouchDesigner with a .toe file.

    Args:
        config: Parsed envoy.json config dict.
        config_path: Path to envoy.json (for resolving relative paths).
        project_path: Optional override .toe path. If relative, resolved
            against the git root (same directory as config_path).
        existing_pids: Optional iterable of TD PIDs already running before
            this launch. Used on macOS to identify the spawned PID by
            exclusion (LaunchServices doesn't return one).
        platform: Override sys.platform, so the darwin spawn path (argv,
            fail-fast, pid resolution) is testable on any machine
            (D-5 Mac-by-construction).
        popen: Override subprocess.Popen for the same reason -- nothing
            real is ever spawned in a test.

    Returns (success: bool, message: str, pid: int|None).
    """
    platform = platform or sys.platform
    popen = popen or subprocess.Popen
    existing_pids = set(existing_pids or [])
    # Resolve TD executable: prefer the install matching the machine-local
    # td_build pin (.embody/local.json; a legacy committed pin is
    # tolerated), then envoy.json's td_executable, then the newest
    # discovered install. select_td_install owns ALL of that policy and
    # handles target_build=None -- it must be called UNCONDITIONALLY: the
    # old `if target_build:` gate made the fresh-clone newest-install
    # fallback unreachable the moment no pin existed (panel blocker --
    # A-14 retires the committed pin, so unpinned is now the normal state
    # for a clone where TD has never run).
    project_config = load_project_config(config_path)
    target_build = project_config.get("td_build")
    fallback_exe = config.get("td_executable")

    td_exe, warning = select_td_install(target_build, fallback_exe)
    if warning:
        log(f"Warning: {warning}")
    if td_exe is None:
        return False, warning or "No TouchDesigner install found", None

    if project_path:
        # Resolve relative paths against git root
        if not os.path.isabs(project_path) and config_path:
            embody_dir = os.path.dirname(os.path.abspath(config_path))
            git_root = os.path.dirname(embody_dir)
            project_path = os.path.join(git_root, project_path)
        toe_path = project_path
    else:
        toe_path = resolve_toe_path(config, config_path)
    if not toe_path:
        return False, "No toe_path configured in envoy.json", None

    # Validate paths
    if platform == "darwin":
        # On macOS, td_executable is the .app bundle path
        if not os.path.exists(td_exe):
            return (False,
                    f"TouchDesigner not found at {td_exe}. "
                    "Install this version or update td_executable in envoy.json",
                    None)
    else:
        if not os.path.isfile(td_exe):
            return (False,
                    f"TouchDesigner executable not found at {td_exe}. "
                    "Install this version or update td_executable in envoy.json",
                    None)

    if not os.path.isfile(toe_path):
        return (False,
                f"Project file not found: {toe_path}",
                None)

    # Launch TD
    log(f"Launching TouchDesigner: {td_exe} with {toe_path}")
    try:
        if platform == "darwin":
            # -n forces a new process even when TouchDesigner is already
            # running. Without it, LaunchServices may reuse an existing
            # window and spawn no new process, breaking multi-instance.
            proc = popen(
                ["open", "-n", "-a", td_exe, toe_path],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )
            # 'open' returns immediately; TD process is spawned by LaunchServices.
            # A nonzero exit means the app never launched -- fail fast instead
            # of burning the pid-poll window and reporting a false success.
            proc.wait(timeout=10)
            if proc.returncode:
                return (False,
                        f"'open' failed with exit code {proc.returncode} -- "
                        f"TouchDesigner did not launch",
                        None)
            # Resolve the spawned pid by polling the snapshot diff until it
            # appears (see wait_for_new_td_pid -- the old fixed 2s single-shot
            # diff missed slow spawns).
            pid = wait_for_new_td_pid(
                existing_pids,
                # Keep the injected platform in force all the way down:
                # otherwise a darwin test on a Windows host would shell
                # out to the REAL tasklist through find_all_td_pids.
                find_pids=lambda: find_all_td_pids(platform=platform))
            if pid is None:
                # LaunchServices handed off but no new TD pid surfaced in
                # the poll window. `open` succeeded, so TD is probably
                # still coming up -- but claiming "(PID None)" while
                # reporting success left state.td_pid None, which silently
                # disables crash detection until the instance registers
                # itself. Say what is actually known.
                log("Launched via 'open' but no new TouchDesigner pid "
                    "appeared within the poll window -- liveness will "
                    "resolve once the instance registers itself.")
                return (True,
                        "TouchDesigner launched (pid not yet resolved -- "
                        "LaunchServices hand-off; it will register itself "
                        "shortly)",
                        None)
        else:
            # win32 and linux both spawn the executable directly and get a
            # real pid back.
            proc = popen(
                [td_exe, toe_path],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )
            pid = proc.pid

        return True, f"TouchDesigner launched (PID {pid})", pid

    except Exception as e:
        return False, f"Failed to launch TouchDesigner: {e}", None


