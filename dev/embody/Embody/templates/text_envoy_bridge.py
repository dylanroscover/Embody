# Streaming SSE transport: two bounds on a forward, never one.
#
# REQUEST_TIMEOUT_S is the cap on a forward, absolute FROM THE FIRST BODY
# BYTE.  It holds over the body because every read is re-armed against
# what is LEFT of it (see _ReadBudget), not merely checked between reads
# -- checking alone let a forward overrun the ceiling by a whole idle
# window.  The status/header phase is NOT covered: urlopen reads the
# status line and headers itself, bounded per-recv only, and every byte
# that arrives resets that timeout, so a header-dribbling local peer can
# run well past the cap before the body phase starts and severs it
# (measured 17x at one byte per 0.5s).  Pre-existing and byte-identical
# to the shipped code -- fixing it means rewriting connection setup, not
# this reader, so the claim is narrowed rather than the code widened.
#
# SSE_IDLE_WINDOW_S bounds the silence BETWEEN frames, and only once a
# stream has established a CADENCE (a second pushed frame).  One frame is
# not a cadence: an operation that announces itself and then works
# silently must keep the full cap -- clamping off a single frame killed
# completed long operations with "Lost connection", which is exactly the
# ceiling progress notifications exist to serve.  Each frame renews the
# allowance, so a stream that keeps talking keeps its full gap.
REQUEST_TIMEOUT_S = 300      # Cap on one forward, from the first body byte
SSE_IDLE_WINDOW_S = 60       # Max silence between frames of a talking stream

# Max bytes handed over per read.  read1 returns as soon as ANY bytes are
# available, so this is a ceiling, not a wait.
_READ_CHUNK_BYTES = 65536

# Per-accumulator ceiling, applied SEPARATELY to each of the three places
# bytes pile up: the plain-JSON fallback mirror, the reader's partial-line
# buffer, and one SSE frame's data fields.  They are INDEPENDENT and can
# hold the same bytes at once, so peak transient memory is a multiple of
# this number, not this number.  Twice Envoy's own 64 MiB body cap, so no
# answer it can legally send trips it; it bounds only the pathological
# peer that is neither SSE-framed nor line-terminated.  An ordinary
# keepalive stream stops the mirror at its FIRST framing line, long before
# any byte count matters.
_MAX_BODY_BYTES = 128 * 1024 * 1024

# Escape hatch (A-46 risk mitigation): read to EOF, then run the SAME
# frame parser over the buffered body.  Never the pre-streaming line
# scanner -- that one returns the first notification AS the answer.
# Pre-streaming semantics means pre-streaming BOUNDS: see forward_to_http.
_STREAM_FALLBACK_ENV = "EMBODY_BRIDGE_NO_STREAM"

